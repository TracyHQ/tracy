#!/usr/bin/env bash
# Rebuild the local stand's app images and hot-swap the running containers — the same thing the
# dev server does automatically on every push to `develop`, done here on the iMac with one command.
#
# WHY THIS EXISTS: the stand builds `tracy/web:dev` and `tracy/host:dev` from a Dockerfile, and a
# merge does NOT reach a running container by itself. After changing anything under `apps/tracy-web`
# or `apps/tracy-host` (or pulling a merge that did), the container keeps serving the OLD image and
# shows a bug that is already fixed in the source — measured many times. This rebuilds the image and
# recreates the containers asked for, leaving postgres/minio/dns untouched.
#
# 🔒 `dsh` IS NOT IN THE DEFAULT SET, AND IT CARRIES THE WORST VERSION OF THIS TRAP. Anything under
# `packages/` — the agent's tools, its injected working rules, the path fence — ships in
# `tracy/dsh:dev`, which is 4 GB and takes minutes, so asking for it on every run would make the
# common case unusable. Ask for it by name, or `all`. When it is left out and the ref being built
# DID touch `packages/`, this script says so rather than leaving a stale agent behind.
#
# 🔒 AND BUILDING THE DSH IMAGE IS NOT ENOUGH ON ITS OWN. `TRACY_DSH_HOME` is bind-mounted over
# `/desk-home`, so the host's `profiles/` — seeded once from an older image — SHADOWS what the new
# image ships. Measured 17/09: image carried the fix, the running container did not, and
# `docker compose up -d` recreated nothing because the image reference had not changed. The seed
# below is the other half of the rebuild, not a nicety.
#
# BY DEFAULT it builds from `origin/develop` (what the dev server ships) through a throwaway
# worktree, so it never bakes in another session's uncommitted edits to the shared checkout. Pass
# `--here` to build from the current working tree instead, when you want to test un-pushed local code.
#
# Usage:
#   scripts/rebuild-local.sh                 # build host+web from origin/develop, recreate both
#   scripts/rebuild-local.sh host            # only tracy-host (the one carrying Playwright/Chromium)
#   scripts/rebuild-local.sh web             # only tracy-web
#   scripts/rebuild-local.sh dsh             # only tracy-dsh — the agent's own image (4 GB, minutes)
#   scripts/rebuild-local.sh all             # host + web + dsh
#   scripts/rebuild-local.sh --here          # build from the current working tree (un-pushed code)
#   scripts/rebuild-local.sh --ref my-branch # build from any git ref
#   scripts/rebuild-local.sh --context <dir> --build-only all
#                                            # build the images from the tree <dir> as it is, tag
#                                            # them $APP_IMAGE_TAG, stamp tracy.commit on all three,
#                                            # and stop there: no deploy/.env, no profile seed, no
#                                            # compose (the nightly QA stand, scripts/qa/stand/)
set -euo pipefail

unset DOCKER_HOST || true   # the local daemon on this iMac, never ssh://macmini (CLAUDE.md)

# 🔒 DO NOT EDIT THIS FILE WHILE IT IS RUNNING. bash reads a script by byte offset as it goes, so
# inserting lines into a running copy shifts everything after the read point and bash resumes in
# the middle of a line. Measured 19/09/2026, editing this very file during a `--here dsh` run:
#
#     scripts/rebuild-local.sh: line 142: TRACY_DSH_HOME: command not found
#     scripts/rebuild-local.sh: line 142: /desk-home: No such file or directory
#
# Line 142 is a COMMENT. The image had already built; what died was `seed_dsh_profiles` — the half
# that makes the container use it — so the run ended with a fresh image, a container still on the
# old one, and three errors that name a line containing nothing executable. A dsh build takes
# minutes; that is exactly the window in which editing feels safe.

REF="origin/develop"
HERE=0
CONTEXT=""
BUILD_ONLY=0
SERVICES=()
while [ $# -gt 0 ]; do
  case "$1" in
    --here) HERE=1 ;;
    --ref)  REF="$2"; shift ;;
    --context) CONTEXT="$2"; shift ;;
    --build-only) BUILD_ONLY=1 ;;
    host|web|dsh) SERVICES+=("$1") ;;
    all) SERVICES=(host web dsh) ;;
    -h|--help) sed -n '2,39p' "$0"; exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
  shift
done
[ ${#SERVICES[@]} -eq 0 ] && SERVICES=(host web)

REPO="$(cd "$(dirname "$0")/.." && pwd)"
DEPLOY="$REPO/deploy"
# `deploy/.env` is gitignored, so it exists only in the SHARED checkout — a worktree running its own
# copy of this script has none. Without it compose runs with every TRACY_* blank and dies only AFTER
# the image build, on a message that names no cause (measured 29/09/2026, run from a worktree:
# `invalid spec: :/site: empty section between colons`, the old container left running). Resolve the
# shared checkout's deploy dir instead, and refuse up front when there is no `.env` anywhere.
# `--build-only` never reads an env file nor runs compose, so it needs none.
if [ "$BUILD_ONLY" -eq 0 ] && [ ! -f "$DEPLOY/.env" ]; then
  SHARED="$(cd "$(git -C "$REPO" rev-parse --path-format=absolute --git-common-dir)/.." && pwd)"
  if [ -f "$SHARED/deploy/.env" ]; then
    DEPLOY="$SHARED/deploy"
    echo "==> $REPO/deploy has no .env (a worktree) — using the shared checkout's: $DEPLOY"
  else
    echo "✖ no deploy/.env in $REPO/deploy nor $SHARED/deploy — compose would run with every TRACY_* blank." >&2
    echo "  Create it first (docs/references/running-tracy-locally.md), then re-run." >&2
    exit 2
  fi
fi
TAG="${APP_IMAGE_TAG:-dev}"

# Resolve the build context: a clean worktree at REF, or the working tree itself.
CTX="$REPO"
WT=""
cleanup() { [ -n "$WT" ] && git -C "$REPO" worktree remove --force "$WT" 2>/dev/null || true; }
if [ -n "$CONTEXT" ]; then
  [ -d "$CONTEXT" ] || { echo "✖ --context $CONTEXT is not a directory" >&2; exit 2; }
  CTX="$(cd "$CONTEXT" && pwd)"
  echo "==> building from the tree at $CTX"
elif [ "$HERE" -eq 0 ]; then
  echo "==> fetching $REF"
  # 🔒 A BARE `git fetch origin` DOES NOT BRING `origin/<branch>` WITH IT. The shared checkout's
  # `remote.origin.fetch` lists develop and one other branch only, so on 24/10/2026
  # `--ref origin/wo/research-again` died on `fatal: invalid reference` while a SHA worked. Fetch the
  # named branch into its own remote-tracking ref, then build from the commit it resolves to.
  case "$REF" in
    origin/*) git -C "$REPO" fetch origin --quiet "+refs/heads/${REF#origin/}:refs/remotes/$REF" ;;
    *) git -C "$REPO" fetch origin --quiet ;;
  esac
  SHA="$(git -C "$REPO" rev-parse --verify --quiet "$REF^{commit}")" || {
    echo "✖ --ref $REF names no commit here (a remote branch is origin/<branch>)" >&2; exit 2; }
  WT="$(mktemp -d "${TMPDIR:-/tmp}/tracy-rebuild.XXXXXX")"
  rmdir "$WT"
  echo "==> checking out $REF (${SHA:0:12}) into a throwaway worktree"
  git -C "$REPO" worktree add --detach --quiet "$WT" "$SHA"
  CTX="$WT"
  trap cleanup EXIT
else
  echo "==> building from the current working tree ($REPO)"
fi

# tracy-web's Dockerfile COPYs three gitignored build artifacts (the harness SPA, the design-page
# SPA, and the ops-cms snapshot). A clean worktree has none, so build them once — bootstrapping
# node_modules from the pnpm store (offline; the lockfile matches, so this only links, not fetches).
# 🔒 A THROWAWAY WORKTREE HAS NO `node_modules`, AND EVERY BUILD HERE NEEDS THEM. Split out of
# `ensure_web_assets` on 19/09/2026 because `build_dsh` needed the same bootstrap and never had it:
# it stages the seeder, `stage-cms-seeder.sh` runs `pnpm --filter @tracy/seeder build`, that build
# produces nothing without dependencies, and the staging dies on the `cp` that follows —
#
#     cp: /tmp/tracy-rebuild.XXXX/packages/cms/tracy-seeder/dist/.: No such file or directory
#
# a message naming a path and not the reason, which is exactly what the comment inside `build_dsh`
# was written to prevent. So `scripts/rebuild-local.sh dsh` — the DOCUMENTED default, which builds
# from `origin/develop` — could not build the dsh image at all; only `--here` worked, because the
# real checkout already has `node_modules`. Measured the same day on this machine.
ensure_node_modules() {
  local ctx="$1"
  [ -d "$ctx/node_modules" ] && return 0
  echo "==> no node_modules in build context — bootstrapping (submodule, dsh, install)"
  ( cd "$ctx"
    git submodule update --init --recursive vendor/tracy/deepseek-harness
    corepack enable pnpm
    # Order matters and CLAUDE.md §5 says why: `dsh:build` runs pnpm INSIDE the submodule, and a
    # root install afterwards is what relinks the members and compiles `fs-ext`.
    pnpm dsh:build
    pnpm install --frozen-lockfile --prefer-offline )
}

ensure_web_assets() {
  local ctx="$1"
  local missing=0
  for p in packages/web/tracy-harness/dist packages/web/tracy-design-page/dist packages/web/tracy-wo-find-page/dist apps/tracy-docs/dist apps/tracy-web/static/ops-cms; do
    [ -e "$ctx/$p" ] || missing=1
  done
  [ "$missing" -eq 0 ] && return 0
  echo "==> web bundles missing in build context — building them"
  ensure_node_modules "$ctx"
  ( cd "$ctx"
    pnpm --filter @tracy/harness-web build
    pnpm --filter @tracy/design-page build
    pnpm --filter @tracy/wo-find-page build
    # The documentation site (S5): generates three pages from the reference tables, then Astro.
    pnpm --filter @tracy/docs build
    node scripts/gen-ops-cms-snapshot.mjs --out apps/tracy-web/static/ops-cms )
}

# The dsh image is built from a different Dockerfile, needs the seeder staged into a gitignored
# directory first, and is pinned to the submodule commit the context carries — so it gets its own
# branch rather than a special case inside the app loop.
build_dsh() {
  local ctx="$1"
  # `dsh/cms/` is gitignored, so a clean worktree has none and the COPY fails with a path that
  # names the directory rather than the reason. Staging it BUILDS the seeder, so the context needs
  # its dependencies first — see `ensure_node_modules`.
  ensure_node_modules "$ctx"
  bash "$ctx/packages/fleet/tracy-fleet-operation/scripts/tools/stage-cms-seeder.sh" >/dev/null
  local commit
  commit="$(git -C "$ctx" ls-tree HEAD vendor/tracy/deepseek-harness | awk '{print $3}')"
  [ -n "$commit" ] || { echo "!! no submodule commit for deepseek-harness in $ctx" >&2; return 1; }
  # Stamp the commit the image was built FROM. Without it the staleness check below has nothing to
  # compare against and would answer "fresh" for ever — a check that cannot fail is worse than none,
  # because it reads as a clean bill of health.
  local built_from
  built_from="$(git -C "$ctx" rev-parse HEAD)"
  echo "==> docker build tracy/dsh:$TAG  (≈4 GB, minutes; DSH_COMMIT=${commit:0:12}, from ${built_from:0:12})"
  docker build -f "$ctx/packages/fleet/tracy-fleet-operation/dsh/Dockerfile" \
    --build-arg DSH_COMMIT="$commit" --label "tracy.commit=$built_from" -t "tracy/dsh:$TAG" "$ctx"
}

# 🔒 THE OTHER HALF OF A DSH REBUILD. `TRACY_DSH_HOME` is bind-mounted over `/desk-home`, so the
# host's own `profiles/` wins over whatever the new image ships. Without this, the image has the fix
# and the container does not — and nothing says so, because `up -d` sees the same image tag and
# recreates nothing. Measured 17/09: `grep -c` in the image answered 2, in the container 0.
seed_dsh_profiles() {
  local home
  # `|| true`: no match fails grep, and under pipefail that killed the script before the warning below.
  home="$(grep -E '^TRACY_DSH_HOME=' "$DEPLOY/.env" 2>/dev/null | sed -n 1p | cut -d= -f2- | sed 's/[[:space:]]*#.*$//' | xargs || true)"
  [ -n "$home" ] || { echo "  ⚠ no TRACY_DSH_HOME in deploy/.env — profiles NOT re-seeded, the container will keep the old plugins" >&2; return 0; }
  [ -d "$home" ] || { echo "  ⚠ TRACY_DSH_HOME ($home) is not a directory — profiles NOT re-seeded" >&2; return 0; }
  echo "==> re-seeding profiles/ into $home (the bind mount shadows the image)"
  docker run --rm --entrypoint sh "tracy/dsh:$TAG" -c 'tar -C /desk-home -cf - profiles' \
    | docker run -i --rm -v "$home":/out alpine tar -C /out -xf -
}

for svc in "${SERVICES[@]}"; do
  if [ "$svc" = "dsh" ]; then
    build_dsh "$CTX"
    [ "$BUILD_ONLY" -eq 1 ] || seed_dsh_profiles
    continue
  fi
  [ "$svc" = "web" ] && ensure_web_assets "$CTX"
  echo "==> docker build tracy/$svc:$TAG  (context: $CTX)"
  if [ "$BUILD_ONLY" -eq 1 ]; then
    # The QA stand's manifest reads which commit each running image was built from.
    docker build -f "$CTX/apps/tracy-$svc/Dockerfile" \
      --label "tracy.commit=$(git -C "$CTX" rev-parse HEAD)" -t "tracy/$svc:$TAG" "$CTX"
  else
    docker build -f "$CTX/apps/tracy-$svc/Dockerfile" -t "tracy/$svc:$TAG" "$CTX"
  fi
done

if [ "$BUILD_ONLY" -eq 1 ]; then
  echo "==> built (--build-only): ${SERVICES[*]} as :$TAG — nothing recreated"
  exit 0
fi

# Left dsh out, but the code that ships inside it moved? Say so. This is the failure the script
# exists to prevent, one image further along: a merge that changed the agent's tools or its injected
# rules reaches nothing until `dsh` is rebuilt, and a stale agent looks exactly like a working one.
if ! printf '%s\n' "${SERVICES[@]}" | grep -x dsh >/dev/null; then
  built_from="$(docker inspect "tracy/dsh:$TAG" --format '{{index .Config.Labels "tracy.commit"}}' 2>/dev/null || true)"
  if [ -z "$built_from" ]; then
    # Either no dsh image, or one built before this script started stamping. Both mean "cannot
    # tell", and cannot-tell is said out loud rather than passed over in silence.
    echo "  · tracy/dsh:$TAG carries no build stamp — cannot tell whether the agent's code is current." >&2
    echo "    Rebuild it once to start the record: $0 dsh" >&2
  elif ! git -C "$REPO" cat-file -e "${built_from}^{commit}" 2>/dev/null; then
    echo "  · tracy/dsh:$TAG was built from ${built_from:0:12}, which this checkout does not have." >&2
  elif ! git -C "$REPO" diff --quiet "$built_from" HEAD -- packages/; then
    echo "  ⚠ packages/ changed since tracy/dsh:$TAG was built (${built_from:0:12}) — the agent is" >&2
    echo "  ⚠ running OLD code. Rebuild it: $0 dsh" >&2
  fi
fi

# Recreate ONLY the app containers. compose.macos.yml is mandatory — a bare `up -d` on a Mac
# silently reverts tracy-host to host networking and every site create then answers 502.
COMPOSE_SVCS=()
for svc in "${SERVICES[@]}"; do COMPOSE_SVCS+=("tracy-$svc"); done
echo "==> recreating: ${COMPOSE_SVCS[*]}"
# 🔒 THE COMPOSE FILES COME FROM THE TREE THE IMAGES WERE BUILT FROM. They were read from the shared
# checkout ($REPO), which lags origin/develop whenever another session sits on an older commit: on
# 25/09/2026 the stand ran develop 722c32bc1 images with the environment of a compose.yml that had no
# TRACY_DEPLOYMENT_ORIGIN, so `page.text`/`page.look` refused every site's own home page as
# REDIRECTED_OFF_SITE (`/ redirects to http://<label>.tracy.test:8080/, which is not this site`).
# `--project-directory "$DEPLOY"` keeps `deploy/.env` (gitignored, only in the shared checkout) and
# every relative bind mount where they were.
# 🔒 AND THE IMAGES ARE THE ONES JUST BUILT. compose reads `${DSH_IMAGE_TAG:-dev}` for tracy-dsh, not
# APP_IMAGE_TAG, and deploy/.env pins DSH_IMAGE_TAG=dev — so on 24/10/2026 a run with
# APP_IMAGE_TAG=local-develop-eeac5aef built tracy/dsh:local-develop-eeac5aef and recreated tracy-dsh
# on the 12/10 tracy/dsh:dev. Name every image and tag here; the shell beats deploy/.env.
compose_up() {
  WEB_IMAGE=tracy/web HOST_IMAGE=tracy/host DSH_IMAGE=tracy/dsh APP_IMAGE_TAG="$TAG" DSH_IMAGE_TAG="$TAG" \
  docker compose --project-directory "$DEPLOY" \
    -f "$CTX/deploy/compose.yml" -f "$CTX/deploy/compose.macos.yml" --profile local \
    up -d --no-deps --force-recreate "$@"
}
# 🔒 TRACY-WEB FIRST, ALONE. compose pins tracy-web to `${TRACY_NETWORK_PREFIX}.10` on the `tracy`
# network while every other container takes a dynamic address. Recreated together, whichever starts
# first can be handed .10 — measured 04/10/2026: tracy-host got it, tracy-web stayed `Created` with
# "failed to set up container networking: Address already in use" and the stand answered nothing.
# Starting tracy-web on its own first lets it claim its address before anything else asks for one.
rest=()
for svc in "${COMPOSE_SVCS[@]}"; do [ "$svc" = tracy-web ] || rest+=("$svc"); done
if [ "${#rest[@]}" -lt "${#COMPOSE_SVCS[@]}" ]; then
  compose_up tracy-web
fi
if [ "${#rest[@]}" -gt 0 ]; then
  compose_up "${rest[@]}"
fi

echo "==> done. running images:"
docker ps --format '  {{.Names}}\t{{.Image}}' | grep -E "tracy-(web|host)-1|tracy-dsh$" || true

# tracy-host MUST land on the compose bridge, not host networking. A bare `up -d` (one that forgets
# compose.macos.yml) silently reverts it to host mode, and then tracy-web cannot resolve the name
# `tracy-host` — every demo/site install answers 502 HOST_REFUSED with all services healthy. Verify
# it here so the trap is loud instead of silent.
if printf '%s\n' "${COMPOSE_SVCS[@]}" | grep -x tracy-host >/dev/null; then
  mode=$(docker inspect tracy-tracy-host-1 --format '{{.HostConfig.NetworkMode}}' 2>/dev/null || echo '?')
  if [ "$mode" = host ]; then
    echo "  ⚠ tracy-host is on HOST networking — tracy-web cannot reach it (502 HOST_REFUSED)." >&2
    echo "  ⚠ Recreate it WITH compose.macos.yml, or re-run this script." >&2
  else
    echo "  tracy-host network: $mode (bridge — tracy-web can reach it)"
  fi
fi
