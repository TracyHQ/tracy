#!/usr/bin/env node
/**
 * Generate the QA stand's env file (tasks/todo-daily-qa.md §4.5, Q22 as amended 03/10/2026).
 *
 *   makeEnv({ exampleFile, templateFile, sourceEnvFile, outFile, qaHome, toolDir,
 *             releasesTokenFile?, force?, randomSecret? }) -> { written: string[] }
 *
 * - Starts from `deploy/.env.example` of the tree under test, applies `env.template`.
 * - Generates fresh secrets for every `{{secret}}`.
 * - Copies from the shared checkout's `deploy/.env` EXACTLY the keys in COPY_ALLOWED
 *   (MODEL_API_KEY). Nothing else is read from that file.
 * - TRACY_RELEASES_GITHUB_TOKEN stays empty unless a token file is named explicitly
 *   (`--releases-token-file`): the shared token is not read-only, so it is never copied.
 * - Forces every DEMO_*, CLOUDFLARE_*, GITHUB_APP_*, GOOGLE_*, GITHUB_OAUTH_* key empty.
 * - Writes mode 0600 via tmp → fsync → rename; refuses to replace an existing file without
 *   `force` (new secrets would sign every open session out and orphan the dsh seat secret).
 * - Never prints a value: the result and the CLI output carry key NAMES only.
 *
 * CLI: node make-env.mjs --src <tree> --source-env <shared deploy/.env> [--out <file>]
 *        [--qa-home <dir>] [--tool-dir <dir>] [--releases-token-file <file>] [--force]
 */
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { atomicWrite, parseEnv, qaHome as defaultQaHome } from './qa-stand.mjs'

export const COPY_ALLOWED = Object.freeze(['MODEL_API_KEY'])
export const FORBIDDEN_PREFIXES = Object.freeze([
  'DEMO_',
  'CLOUDFLARE_',
  'GITHUB_APP_',
  'GOOGLE_',
  'GITHUB_OAUTH_'
])
export const isForbidden = (key) => FORBIDDEN_PREFIXES.some((p) => key.startsWith(p))

const HERE = path.dirname(fileURLToPath(import.meta.url))

function readTemplate(file) {
  const entries = []
  for (const raw of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim()
    if (line === '' || line.startsWith('#')) continue
    const i = line.indexOf('=')
    if (i < 1) throw new Error(`env.template: not KEY=value: ${line.slice(0, 40)}`)
    entries.push([line.slice(0, i), line.slice(i + 1)])
  }
  return entries
}

export function makeEnv({
  exampleFile,
  templateFile = path.join(HERE, 'env.template'),
  sourceEnvFile,
  outFile,
  qaHome,
  toolDir,
  releasesTokenFile = null,
  force = false,
  randomSecret = () => randomBytes(32).toString('hex')
}) {
  if (!path.isAbsolute(qaHome) || !path.isAbsolute(toolDir))
    throw new Error('qaHome and toolDir must be absolute paths')
  if (existsSync(outFile) && !force)
    throw new Error(`${outFile} exists — refusing to rotate its secrets (pass --force)`)
  const example = parseEnv(readFileSync(exampleFile, 'utf8'))
  const source = sourceEnvFile ? parseEnv(readFileSync(sourceEnvFile, 'utf8')) : new Map()
  let releasesToken = ''
  if (releasesTokenFile) {
    releasesToken = readFileSync(releasesTokenFile, 'utf8').trim()
    if (/\s/.test(releasesToken)) throw new Error('releases token file must hold one token on one line')
  }

  const values = new Map(example)
  for (const [key, tmpl] of readTemplate(templateFile)) {
    let v = tmpl.replaceAll('{{QA_HOME}}', qaHome).replaceAll('{{QA_TOOL_DIR}}', toolDir)
    if (v === '{{secret}}') v = randomSecret()
    else if (v === '{{releases-token}}') v = releasesToken
    else {
      const m = /^\{\{copy:([A-Z0-9_]+)\}\}$/.exec(v)
      if (m) {
        if (!COPY_ALLOWED.includes(m[1])) throw new Error(`env.template copies ${m[1]}, which is not allowed`)
        v = source.get(m[1]) ?? ''
      }
    }
    if (/\{\{/.test(v)) throw new Error(`env.template: unknown marker in ${key}`)
    values.set(key, v)
  }
  for (const key of values.keys()) if (isForbidden(key)) values.set(key, '')

  const lines = ['# Generated by scripts/qa/stand/make-env.mjs — do not edit by hand; regenerate.']
  for (const [k, v] of values) {
    if (/[\s#"'$]/.test(v)) throw new Error(`value of ${k} needs quoting, which this file does not do`)
    lines.push(`${k}=${v}`)
  }
  atomicWrite(outFile, `${lines.join('\n')}\n`, 0o600)
  return { written: [...values.keys()].filter((k) => values.get(k) !== '') }
}

function parseArgs(argv) {
  const o = { force: false }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    const next = () => argv[++i]
    if (a === '--src') o.src = next()
    else if (a === '--source-env') o.sourceEnv = next()
    else if (a === '--out') o.out = next()
    else if (a === '--qa-home') o.qaHome = next()
    else if (a === '--tool-dir') o.toolDir = next()
    else if (a === '--releases-token-file') o.releasesTokenFile = next()
    else if (a === '--force') o.force = true
    else throw new Error(`unknown argument: ${a}`)
  }
  return o
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const o = parseArgs(process.argv.slice(2))
    if (!o.src || !o.sourceEnv) throw new Error('--src and --source-env are required')
    const home = path.resolve(o.qaHome ?? defaultQaHome())
    const { written } = makeEnv({
      exampleFile: path.join(o.src, 'deploy', '.env.example'),
      sourceEnvFile: o.sourceEnv,
      outFile: path.resolve(o.out ?? path.join(home, '.env')),
      qaHome: home,
      toolDir: path.resolve(o.toolDir ?? path.join(home, '..', '..', 'TCH-worktrees', 'qa-tool')),
      releasesTokenFile: o.releasesTokenFile ?? null,
      force: o.force
    })
    console.log(`wrote ${written.length} non-empty keys: ${written.join(' ')}`)
  } catch (error) {
    console.error(`make-env: ${error.message}`)
    process.exit(1)
  }
}
