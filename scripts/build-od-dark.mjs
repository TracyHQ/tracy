#!/usr/bin/env node
/**
 * Generate `vendor/tracy/od-design-system/dark.json`: for each of the 152 systems, whether its fixture can
 * be shown dark by the token override alone, and the literal paints that say no.
 *
 * WHY A GENERATOR. "Dark" in the preview dialog is one override block laid over the author's CSS;
 * it repaints tokens, `body` and `.page`, and nothing else. A fixture that paints an input `#ffffff`
 * or a heading `#111` stays that way and reads as a light block or ink on ink. The judge
 * (`lib/od-dark-rules.mjs`) is deterministic, so the verdict is DATA shipped in the image and the
 * dialog only reads a boolean — no browser, no guess, and the same answer on every lane.
 *
 * Usage:  node scripts/build-od-dark.mjs            # writes dark.json
 *         node scripts/build-od-dark.mjs --check    # exits 1 when dark.json is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { darkReport } from './lib/od-dark-rules.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PKG = path.join(ROOT, 'vendor', 'tracy', 'od-design-system')
const SYSTEMS = path.join(PKG, 'systems')
const OUT = path.join(PKG, 'dark.json')
const check = process.argv.includes('--check')

function build() {
  const ids = readdirSync(SYSTEMS)
    .filter((d) => existsSync(path.join(SYSTEMS, d, 'components.html')))
    .sort()
  const systems = {}
  let safe = 0
  for (const id of ids) {
    const r = darkReport(readFileSync(path.join(SYSTEMS, id, 'components.html'), 'utf8'))
    if (r.safe) safe++
    systems[id] = { safe: r.safe, lightBg: r.lightBg, darkText: r.darkText }
  }
  return {
    schemaVersion: 'tracy-od-dark/v1',
    note: 'Generated by scripts/build-od-dark.mjs from systems/*/components.html — do not edit; rerun the script.',
    rule: 'safe = no literal background with luminance >= 0.5 and no literal text colour with luminance <= 0.25 outside html/body/.page; color-mix() and alpha < 0.5 are ignored',
    systems,
    summary: { systems: ids.length, safe, unsafe: ids.length - safe }
  }
}

const next = `${JSON.stringify(build(), null, 1)}\n`
if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== next) {
    console.error('build-od-dark: dark.json is stale — run `node scripts/build-od-dark.mjs`.')
    process.exit(1)
  }
  console.log('build-od-dark: dark.json matches the fixtures.')
} else {
  writeFileSync(OUT, next)
  const doc = JSON.parse(next)
  console.log(
    `build-od-dark: ${String(doc.summary.systems)} systems, ${String(doc.summary.safe)} dark-safe, ${String(doc.summary.unsafe)} not`
  )
}
