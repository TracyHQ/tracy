#!/usr/bin/env node
/**
 * Generate `vendor/tracy/od-design-system/slots.json`: for each of the 152 systems, the text slots of its
 * `components.html` — where a customer's words can go, what role each slot plays, and how long the
 * author's own words were there (spec §4f decision 2).
 *
 * WHY A GENERATOR AND NOT THE BROWSER. The card and the dialog must put the same words in the same
 * places; an agent must be able to fill a FORM of slots without ever touching HTML; and the same
 * numbering must hold on every lane. One deterministic pass over the vendored fixtures, committed
 * as data and shipped in the image, gives all three. The DOM here is linkedom, whose
 * `querySelectorAll` order is document order — the same order a browser's DOMParser yields, which
 * is what `slots[].n` relies on.
 *
 * Usage:  node scripts/build-od-slots.mjs            # writes slots.json
 *         node scripts/build-od-slots.mjs --check    # exits 1 when slots.json is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { slotsOf } from './lib/od-slots-dom.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PKG = path.join(ROOT, 'vendor', 'tracy', 'od-design-system')
const SYSTEMS = path.join(PKG, 'systems')
const OUT = path.join(PKG, 'slots.json')
/**
 * The six artifacts (`system/artifacts/<kind>.html`) are the brand engine's output from ONE template per
 * kind, so their slot map is the same for every system that has them — measured 06/09: one shape across
 * 150 systems, only word counts moving where the system's name appears. One shared map per kind lives in
 * the design-inspiration plugin (bundled into its host), taken from the `default` system; a second shape would
 * mean upstream changed the template, and this script refuses so the map is looked at, not silently split.
 */
const ARTIFACT_OUT = path.join(
  ROOT,
  'packages',
  'design',
  'tracy-design-inspiration',
  'src',
  'host',
  'artifact-slots.json'
)
const ARTIFACT_KINDS = ['landing', 'deck', 'poster', 'email', 'newsletter', 'form']
const ARTIFACT_SOURCE = 'default'
const check = process.argv.includes('--check')

function buildArtifacts(ids) {
  const artifacts = {}
  for (const kind of ARTIFACT_KINDS) {
    let shared = null
    const shapes = new Set()
    for (const id of ids) {
      const file = path.join(SYSTEMS, id, 'system', 'artifacts', `${kind}.html`)
      if (!existsSync(file)) continue
      const slots = slotsOf(readFileSync(file, 'utf8'), [])
      shapes.add(slots.map((x) => `${x.id}:${x.role}`).join('|'))
      if (id === ARTIFACT_SOURCE) shared = slots
    }
    if (shapes.size !== 1 || shared === null) {
      console.error(
        `build-od-slots: artifacts/${kind}.html has ${String(shapes.size)} slot shapes across the systems (expected one) — upstream changed the template; decide before regenerating.`
      )
      process.exit(1)
    }
    artifacts[kind] = shared
  }
  return {
    schemaVersion: 'tracy-od-slots/v1',
    note: `Generated by scripts/build-od-slots.mjs from systems/${ARTIFACT_SOURCE}/system/artifacts/*.html — one template per kind for all systems; do not edit.`,
    artifacts
  }
}

function build() {
  const ids = readdirSync(SYSTEMS)
    .filter((d) => existsSync(path.join(SYSTEMS, d, 'components.html')))
    .sort()
  const systems = {}
  const roleTotals = {}
  for (const id of ids) {
    const html = readFileSync(path.join(SYSTEMS, id, 'components.html'), 'utf8')
    let groups = []
    const manifestPath = path.join(SYSTEMS, id, 'components.manifest.json')
    if (existsSync(manifestPath)) {
      try {
        groups = JSON.parse(readFileSync(manifestPath, 'utf8')).groups ?? []
      } catch {
        groups = []
      }
    }
    const slots = slotsOf(html, groups)
    for (const s of slots) roleTotals[s.role] = (roleTotals[s.role] ?? 0) + 1
    const byRole = {}
    for (const s of slots) byRole[s.role] = (byRole[s.role] ?? 0) + 1
    systems[id] = { count: slots.length, byRole, slots }
  }
  return {
    schemaVersion: 'tracy-od-slots/v1',
    note: 'Generated by scripts/build-od-slots.mjs from systems/*/components.html — do not edit; rerun the script.',
    systems,
    summary: {
      systems: ids.length,
      slots: Object.values(systems).reduce((a, s) => a + s.count, 0),
      roles: roleTotals
    }
  }
}

const built = build()
const next = `${JSON.stringify(built, null, 1)}\n`
const nextArtifacts = `${JSON.stringify(buildArtifacts(Object.keys(built.systems)), null, 1)}\n`
if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== next) {
    console.error('build-od-slots: slots.json is stale — run `node scripts/build-od-slots.mjs`.')
    process.exit(1)
  }
  const currentArtifacts = existsSync(ARTIFACT_OUT) ? readFileSync(ARTIFACT_OUT, 'utf8') : ''
  if (currentArtifacts !== nextArtifacts) {
    console.error(
      'build-od-slots: tracy-design-inspiration/src/host/artifact-slots.json is stale — run `node scripts/build-od-slots.mjs`.'
    )
    process.exit(1)
  }
  console.log('build-od-slots: slots.json and artifact-slots.json match the fixtures.')
} else {
  writeFileSync(OUT, next)
  writeFileSync(ARTIFACT_OUT, nextArtifacts)
  const doc = JSON.parse(next)
  console.log(
    `build-od-slots: ${String(doc.summary.systems)} systems, ${String(doc.summary.slots)} slots — ` +
      Object.entries(doc.summary.roles)
        .sort((a, b) => b[1] - a[1])
        .map(([r, n]) => `${r} ${String(n)}`)
        .join(' · ')
  )
}
