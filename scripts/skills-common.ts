/**
 * Shared base of `skills:sync` and `skills:check`.
 *
 * WHY TWO FOLDERS. The skill source is `.agents/skills/` — neutral, tied to no one tool.
 * `.claude/skills/` is a **symlink mirror** so Claude Code can see them. A real copy there is two
 * sources of truth, and the second drifts silently — exactly the failure BOUNDARY RULE #2 names
 * ("a copy = a drift bomb").
 *
 * WHY A WHITELIST. `public-skills.txt` lists which skills belong to the repo. Everything else in
 * `.agents/skills/` is one machine's — an experiment, a private skill — and is excluded by the
 * generated `.gitignore`. So playing with skills in the repo cannot be committed by accident.
 */
import * as fs from 'node:fs'
import * as path from 'node:path'

export const ROOT_DIR = path.join(import.meta.dirname, '..')
export const AGENTS_SKILLS_DIR = path.join(ROOT_DIR, '.agents', 'skills')
export const CLAUDE_SKILLS_DIR = path.join(ROOT_DIR, '.claude', 'skills')
export const AGENTS_SKILLS_GITIGNORE = path.join(AGENTS_SKILLS_DIR, '.gitignore')
export const CLAUDE_SKILLS_GITIGNORE = path.join(CLAUDE_SKILLS_DIR, '.gitignore')
export const PUBLIC_SKILLS_FILE = path.join(AGENTS_SKILLS_DIR, 'public-skills.txt')

/**
 * Skills from ANOTHER repo that this tree carries in `vendor/` (ADR 0006: a subtree pinned to one commit).
 * They are not in `.agents/skills/` — their home is the other repo — but Claude Code must still see
 * them, so the `.claude/skills/<name>` mirror points straight into the vendor tree. Editing them here
 * edits the wrong place: read that vendor's `IMPORT-NOTE.md` first.
 */
export const VENDORED_SKILLS: Record<string, string> = {
  'tracy-emdash-template': path.join(
    'vendor',
    'emdash',
    'tracy-emdash-skill',
    'skills',
    'tracy-emdash-template'
  ),
  // The T4 skill builds a Joomla template, and since 1.3.0 it carries the shared layer and the 30
  // review gates an agent needs to measure one. It was vendored but never mirrored, so nothing on
  // this machine could invoke it by name.
  'joomlart-t4-template': path.join('vendor', 'joomla', 'joomlart-t4-skill', 'skills', 'joomlart-t4-template')
}

/** kebab-case — the same convention as Worker folder names (docs/references/naming-conventions.md §1). */
const SKILL_NAME_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

export function readFileSafe(filePath: string): string | null {
  if (!fs.existsSync(filePath)) return null
  return fs.readFileSync(filePath, 'utf-8')
}

export function listSkillNames(): string[] {
  const content = readFileSafe(PUBLIC_SKILLS_FILE)
  if (content === null) {
    throw new Error('.agents/skills/public-skills.txt does not exist')
  }

  const names: string[] = []
  const seen = new Set<string>()

  for (const [index, rawLine] of content.split('\n').entries()) {
    const line = rawLine.trim()
    if (line === '' || line.startsWith('#')) continue

    // A trailing comment would end up in the folder name and cause a hard-to-read error later.
    if (line.includes('#')) {
      throw new Error(
        `trailing comments are not allowed at .agents/skills/public-skills.txt:${index + 1}; ` +
          'move the comment to the line above'
      )
    }
    if (!SKILL_NAME_PATTERN.test(line)) {
      throw new Error(`invalid skill name '${line}' at .agents/skills/public-skills.txt:${index + 1}`)
    }
    if (seen.has(line)) {
      throw new Error(`duplicate skill name '${line}' at .agents/skills/public-skills.txt:${index + 1}`)
    }

    seen.add(line)
    names.push(line)
  }

  return names.sort((a, b) => a.localeCompare(b))
}

export function buildAgentsSkillsGitignore(skillNames: string[]): string {
  const lines = [
    '# GENERATED by `pnpm skills:sync`. Do not edit by hand.',
    '# Ignore everything, then re-include exactly the skills listed in public-skills.txt.',
    '*',
    '!.gitignore',
    '!README*.md',
    '!public-skills.txt'
  ]
  for (const name of skillNames) {
    lines.push(`!${name}/`, `!${name}/**`)
  }
  // A skill may carry its own `npm install` (tracy-wordpress-theme: jsdom + playwright, since
  // its tools run from the skill dir, unlike the emdash kit that runs from the template's
  // node_modules). `!<name>/**` above re-includes everything under the skill and beats the
  // root `node_modules/` rule — a later, more specific negation wins in git — so the
  // dependency tree would land in git on the first `git add -A`. Re-ignore it here, after the
  // whitelist, where it wins.
  lines.push('**/node_modules/')
  return `${lines.join('\n')}\n`
}

export function buildClaudeSkillsGitignore(skillNames: string[]): string {
  const lines = ['# GENERATED by `pnpm skills:sync`. Do not edit by hand.', '*', '!.gitignore', '!README*.md']
  for (const name of [...skillNames, ...Object.keys(VENDORED_SKILLS)].sort((a, b) => a.localeCompare(b))) {
    lines.push(`!${name}`)
  }
  return `${lines.join('\n')}\n`
}

export function writeFileIfChanged(filePath: string, content: string): boolean {
  if (readFileSafe(filePath) === content) return false
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, content, 'utf-8')
  return true
}

/** Symlink target, relative to `.claude/skills/` — must match the check character for character. */
export function claudeSymlinkTarget(skillName: string): string {
  const vendored = VENDORED_SKILLS[skillName]
  if (vendored !== undefined) return path.join('..', '..', vendored)
  return path.join('..', '..', '.agents', 'skills', skillName)
}

/** A skill's source on disk: `.agents/skills/<name>`, or the vendor tree for a vendored skill. */
export function skillSourceDir(skillName: string): string {
  const vendored = VENDORED_SKILLS[skillName]
  return vendored === undefined ? path.join(AGENTS_SKILLS_DIR, skillName) : path.join(ROOT_DIR, vendored)
}

/** Every skill Claude Code must see: this repo's, plus the vendored ones. */
export function allMirroredSkillNames(skillNames: string[]): string[] {
  return [...skillNames, ...Object.keys(VENDORED_SKILLS)].sort((a, b) => a.localeCompare(b))
}
