// The words Tracy SaaS says itself, in every language of the cleaned site-language list (TCH #1013, T25b, decision O5).
//
// 🔒 THE SITE'S LANGUAGE, NOT THE STORED LOCALE. The template stores one locale (`en`), and a customer who picks another
// language gets that root written in it (`tools/personalize.mjs` `localesFrom`, `display-locale.json`
// `{ "en": "vi-VN" }`). So these words are looked up by the DISPLAY tag (`uiTag` in `src/lib/i18n.ts`): the exact tag
// first (`zh-tw`, `pt-pt`), then its language (`zh`, `pt`), then English. A language missing here reads as English,
// never as a blank.
//
// Dates are not spelled here: ICU knows how every language writes a month (`uiDate`), and the Gregorian calendar is named
// so a Thai site never prints the Buddhist year. Counts go through `Intl.PluralRules` (`uiCount`): a language with
// more than two plural forms lists them, a language that names none falls back to `other`.
//
// Pure (no file, no EmDash), so a plain `node --test` holds it: tests/ui-words.test.mjs.

