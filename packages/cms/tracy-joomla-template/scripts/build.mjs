const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ROOT = path.resolve(PKG, '..', '..', '..')
const VENDOR = path.join(ROOT, 'vendor', 'tracy', 'od-design-system')
const SRC = path.join(PKG, 'src', 'tpl_tracy')
const DIST = path.join(PKG, 'dist')
const INSPIRATIONS_DIR = 'media/css/inspirations'
const FIXTURES_DIR = 'media/css/fixtures'
const ARTIFACTS_DIR = 'media/css/artifacts'
const GENERATED_NOTE =
  'Generated by scripts/build.mjs from vendor/tracy/od-design-system — do not edit; rerun the build.'

/** @param {string} s */
function escapeXml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

/**
 * Everything the build would write, in memory, so `--check` and the real build share one truth.
 * @param {{ vendorDir: string, srcDir: string, version: string }} opts
 * @returns {{ files: Map<string, string>, ids: string[] }}
 */
export function plan({ vendorDir, srcDir, version }) {
  const catalog = JSON.parse(readFileSync(path.join(vendorDir, 'catalog.json'), 'utf8'))
  if (!Array.isArray(catalog.systems)) throw new Error('catalog.json has no systems[]')
  if (catalog.count !== catalog.systems.length) {
    throw new Error(
      `catalog.json count ${String(catalog.count)} disagrees with its ${String(catalog.systems.length)} rows`
    )
  }
  const darkPath = path.join(vendorDir, 'dark.json')
  const dark = existsSync(darkPath) ? (JSON.parse(readFileSync(darkPath, 'utf8')).systems ?? {}) : {}

  const files = new Map()
  const systems = {}
  const rows = [...catalog.systems].sort((a, b) => (a.id < b.id ? -1 : 1))
  for (const row of rows) {
    const tokensPath = path.join(vendorDir, 'systems', row.id, 'tokens.css')
    if (!existsSync(tokensPath))
      throw new Error(`${row.id}: catalog names it but systems/${row.id}/tokens.css is missing`)
    const css = readFileSync(tokensPath, 'utf8')
    // Comments mention `:root { … }` too; only code counts. A second `:root` inside a media query
    // (reduced motion, a language) is legitimate — the contract is the 56 names, not one block.
    const code = css.replace(/\/\*[\s\S]*?\*\//g, '')
    if (!/:root\s*\{/.test(code)) throw new Error(`${row.id}: tokens.css declares no :root block`)
    const missing = TOKEN_NAMES.filter((name) => !new RegExp(`^\\s*${name}\\s*:`, 'm').test(code))
    if (missing.length > 0) throw new Error(`${row.id}: tokens.css is missing ${missing.join(', ')}`)
    files.set(`${INSPIRATIONS_DIR}/${row.id}.css`, css)
    // The system's own fixture stylesheet, fenced under .tracy-fixture: the home page kind
    // `fixture` renders components.html pixel for pixel as the preview dialog showed it.
    const fixturePath = path.join(vendorDir, 'systems', row.id, 'components.html')
    if (existsSync(fixturePath)) {
      const parts = fixtureParts(readFileSync(fixturePath, 'utf8'))
      files.set(
        `${FIXTURES_DIR}/${row.id}.css`,
        `/* ${row.id} — components.html of OpenDesign, fenced. ${GENERATED_NOTE} */\n${scopeFixtureCss(parts.css)}`
      )
    }
    // The engine's page artifacts (landing, form, typography), built here at the same engine
    // version the preview host uses, each fenced under .tracy-artifact: the page kind `artifact`.
    const designPath = path.join(vendorDir, 'systems', row.id, 'DESIGN.md')
    const docs = buildArtifactDocs({
      id: row.id,
      name: row.name,
      category: row.category,
      tokensCss: css,
      designMd: existsSync(designPath) ? readFileSync(designPath, 'utf8') : ''
    })
    for (const kind of ARTIFACT_KINDS) {
      files.set(
        `${ARTIFACTS_DIR}/${kind}/${row.id}.css`,
        `/* ${row.id} — ${kind} artifact of the brand engine, fenced. ${GENERATED_NOTE} */\n${scopeFixtureCss(fixtureParts(docs[kind]).css, ARTIFACT_WRAPPER)}`
      )
    }
    systems[row.id] = {
      name: row.name,
      category: row.category,
      nav: row.nav,
      hero: row.hero,
      dark: dark[row.id]?.safe === true
    }
  }
  const ids = Object.keys(systems)

  // `default` first so the admin list opens on the neutral system, then alphabetical.
  const ordered = [...ids].sort((a, b) => (a === 'default' ? -1 : b === 'default' ? 1 : a < b ? -1 : 1))
  const options = ordered
    .map(
      (id) =>
        `          <option value="${id}">${escapeXml(systems[id].name)} (${escapeXml(systems[id].category)})</option>`
    )
    .join('\n')
  const tpl = readFileSync(path.join(srcDir, 'templateDetails.tpl.xml'), 'utf8')
  const xml = tpl
    .replace(/<!--[\s\S]*?-->\n/, `<!-- ${GENERATED_NOTE} Source: templateDetails.tpl.xml -->\n`)
    .replace('@@VERSION@@', version)
    .replace('@@INSPIRATION_OPTIONS@@', options)
  if (xml.includes('@@')) throw new Error('templateDetails.tpl.xml has a placeholder the build does not know')
  files.set('templateDetails.xml', xml)
  files.set(
    'inspirations.json',
    `${JSON.stringify({ schemaVersion: 'tracy-joomla-inspirations/v1', note: GENERATED_NOTE, systems }, null, 2)}\n`
  )
  return { files, ids }
}

/**
 * Planned files that differ from disk, plus token files on disk that no system produced.
 * @param {Map<string, string>} files
 * @param {string} srcDir
 * @returns {string[]}
 */
export function stale(files, srcDir) {
  const report = []
  for (const [rel, content] of files) {
    const abs = path.join(srcDir, rel)
    if (!existsSync(abs) || readFileSync(abs, 'utf8') !== content) report.push(rel)
  }
  for (const dirRel of [
    INSPIRATIONS_DIR,
    FIXTURES_DIR,
    ...ARTIFACT_KINDS.map((k) => `${ARTIFACTS_DIR}/${k}`)
  ]) {
    const dir = path.join(srcDir, dirRel)
    if (!existsSync(dir)) continue
    for (const name of readdirSync(dir)) {
      const rel = `${dirRel}/${name}`
      if (name.endsWith('.css') && !files.has(rel)) report.push(rel)
    }
  }
  return report
}

function main() {
  const check = process.argv.includes('--check')
  const version = JSON.parse(readFileSync(path.join(PKG, 'package.json'), 'utf8')).version
  const asset = JSON.parse(readFileSync(path.join(SRC, 'joomla.asset.json'), 'utf8'))
  if (asset.version !== version) {
    console.error(
      `build: joomla.asset.json says ${String(asset.version)}, package.json says ${version} — keep them equal.`
    )
    process.exit(1)
  }
  const { files, ids } = plan({ vendorDir: VENDOR, srcDir: SRC, version })

  if (check) {
    const report = stale(files, SRC)
    if (report.length > 0) {
      for (const rel of report)
        console.error(`build: packages/cms/tracy-joomla-template/src/tpl_tracy/${rel} is stale`)
      console.error('build: run `pnpm --filter @tracy/joomla-template build`.')
      process.exit(1)
    }
    console.log(`build: ${String(ids.length)} design systems, generated files match the vendor library.`)
    return
  }

  for (const [rel, content] of files) {
    const abs = path.join(SRC, rel)
    mkdirSync(path.dirname(abs), { recursive: true })
    writeFileSync(abs, content)
  }
  mkdirSync(DIST, { recursive: true })
  const zipPath = path.join(DIST, `tpl_tracy-${version}.zip`)
  if (existsSync(zipPath)) execFileSync('rm', [zipPath])
  // The manifest must sit at the zip root, hence zipping from inside the template directory.
  execFileSync('zip', ['-qrX', zipPath, '.', '-x', '*.DS_Store', '*.tpl.xml'], { cwd: SRC })
  const listing = execFileSync('unzip', ['-l', zipPath], { encoding: 'utf8' })
  const entries = listing.split('\n').map((line) => line.trim().split(/\s+/).pop() ?? '')
  if (!entries.includes('templateDetails.xml')) throw new Error('zip: templateDetails.xml is not at the root')
  if (entries.includes('templateDetails.tpl.xml'))
    throw new Error('zip: the .tpl.xml source leaked into the package')
  const tokens = entries.filter((e) => e.startsWith(`${INSPIRATIONS_DIR}/`) && e.endsWith('.css')).length
  if (tokens !== ids.length)
    throw new Error(`zip: ${String(tokens)} token files, expected ${String(ids.length)}`)
  const fixtures = entries.filter((e) => e.startsWith(`${FIXTURES_DIR}/`) && e.endsWith('.css')).length
  if (fixtures !== ids.length)
    throw new Error(`zip: ${String(fixtures)} fixture files, expected ${String(ids.length)}`)
  const artifacts = entries.filter((e) => e.startsWith(`${ARTIFACTS_DIR}/`) && e.endsWith('.css')).length
  if (artifacts !== ids.length * ARTIFACT_KINDS.length)
    throw new Error(
      `zip: ${String(artifacts)} artifact files, expected ${String(ids.length * ARTIFACT_KINDS.length)}`
    )
  copyFileSync(zipPath, path.join(DIST, 'tpl_tracy.zip'))
  const bytes = readFileSync(zipPath).length
  console.log(
    `build: ${String(ids.length)} design systems → ${path.relative(ROOT, zipPath)} (${String(Math.round(bytes / 1024))} KB)`
  )
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
