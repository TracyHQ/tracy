#!/usr/bin/env node
// Generate the Mermaid diagrams in README.md ("Site at a glance") from the template's own
// sources, so the picture an administrator reads is the site that ships and not a drawing that
// was right once. Nothing here is typed by hand: every node comes from seed/seed.json (schema,
// taxonomies, menus, content), template.config.json (locales, forms, mail), the router
// (src/pages/[...path].astro) and the views (which collections each one reads).
//   node tools/diagrams.mjs           # rewrite the block between the markers in README.md
//   node tools/diagrams.mjs --check   # exit 1 when README.md is not what the sources say
// Five diagrams, one question each: site map · page layout · where to edit what · content
// model · what happens on submit/publish.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
if (args.includes('--help')) {
  console.log(
    'node tools/diagrams.mjs [--check]\nRegenerate the README diagrams; --check compares without writing.'
  )
  process.exit(0)
}
if (args.some((a) => a !== '--check')) throw new Error('Unknown argument; use --help')
const check = args.includes('--check')
const root = process.cwd()
const read = (rel) => readFileSync(path.join(root, rel), 'utf8')
const json = (rel) => JSON.parse(read(rel))

const seed = json('seed/seed.json')
const config = json('template.config.json')
const router = read('src/pages/[...path].astro')
const START = '<!-- diagrams:start — generated by tools/diagrams.mjs, do not edit by hand -->'
const END = '<!-- diagrams:end -->'

// ---------- sources → facts ----------
const locale = config.defaultLocale
const collections = seed.collections.map((c) => ({
  slug: c.slug,
  label: c.label,
  url: c.urlPattern ?? null,
  fields: c.fields,
  count: (seed.content?.[c.slug] ?? []).filter((e) => (e.locale ?? locale) === locale).length
}))
// A singleton is one entry per locale behind a fixed path (the site chrome has no path at all);
// a list holds several entries, each with a slug or, like vacancies, embedded in another page.
for (const c of collections) c.singleton = c.count <= 1 && !(c.url ?? '').includes('{slug}')
const bySlug = Object.fromEntries(collections.map((c) => [c.slug, c]))
const taxonomies = seed.taxonomies
  .filter((t) => t.locale === locale)
  .map((t) => ({
    name: t.name,
    label: t.label,
    collections: t.collections,
    terms: t.terms.map((x) => x.name ?? x.slug)
  }))
const menus = seed.menus
  .filter((m) => m.locale === locale)
  .map((m) => ({ name: m.name ?? m.slug, items: m.items }))
const references = collections.flatMap((c) =>
  c.fields
    .map((f) => ({ f, to: f.validation?.targetCollection ?? f.options?.collection }))
    .filter(({ f, to }) => f.type === 'reference' && to)
    .map(({ f, to }) => ({ from: c.slug, field: f.slug, to }))
)
const formBindings = config.forms.bindings

// Routes, read from the router's own conditions: `a === "about"` for one-segment paths,
// `a === "news" && SLUG.test(b)` for details, `a === "news" && b === "category"` for archives.
const routes = []
if (/segs\.length === 0\) view = \{ component: Home/.test(router)) routes.push({ path: '/', view: 'Home' })
for (const m of router.matchAll(/a === ["']([a-z0-9]+)["']\)?\s*view = \{ component: (\w+)/g))
  routes.push({ path: `/${m[1]}`, view: m[2] })
for (const m of router.matchAll(
  /a === ["']([a-z0-9]+)["'] && SLUG\.test\(b\)\)\s*view = \{ component: (\w+)/g
))
  routes.push({ path: `/${m[1]}/{slug}`, view: m[2] })
for (const m of router.matchAll(
  /a === ["']([a-z0-9]+)["'] && b === ["']([a-z0-9]+)["'] && SLUG\.test\(c\)\)\s*view = \{ component: (\w+)/g
))
  routes.push({ path: `/${m[1]}/${m[2]}/{term}`, view: m[3] })
if (/a === ["']kit["'] && KIT\[b\]/.test(router)) routes.push({ path: '/kit/{page}', view: 'Kit' })
if (/SLUG\.test\(a\)\) view = \{ component: Page/.test(router)) routes.push({ path: '/{slug}', view: 'Page' })
if (routes.length < 12)
  throw new Error(`Router parse found only ${routes.length} routes; the router changed shape`)

// Which collections and menus each view (and the shared chrome) reads.
const readsOf = (src) => ({
  entries: [
    ...new Set(
      [
        ...src.matchAll(/getEmDash(?:Entry|Collection)\(["']([a-z_]+)["']/g),
        // A reference field's entries, read through src/lib/references.ts.
        ...src.matchAll(/referencedEntry\([^,]+,[^,]+,\s*["']([a-z_]+)["']/g)
      ]
        .sort((a, b) => a.index - b.index)
        .map((m) => m[1])
    )
  ],
  menus: [...new Set([...src.matchAll(/getMenu\(["']([a-z_]+)["']/g)].map((m) => m[1]))],
  taxonomies: [
    ...new Set(
      [
        ...src.matchAll(
          /(?:getTaxonomyTerms|getTermsForEntries)\(["'][a-z_]+["'],\s*(?:[^,]+,\s*)?["']([a-z_]+)["']/g
        )
      ].map((m) => m[1])
    )
  ]
})
const views = Object.fromEntries(
  readdirSync(path.join(root, 'src/views'))
    .filter((f) => f.endsWith('.astro'))
    .map((f) => [f.replace('.astro', ''), readsOf(read(`src/views/${f}`))])
)
const chrome = readsOf(read('src/lib/chrome.ts'))
// The frame prints the site singleton on every page; the latest projects and posts it also reads
// for the mega menu are still content of their own pages, so only `site` is treated as chrome.
const chromeEntries = new Set(['site'])

// ---------- helpers ----------
const id = (s) => s.replace(/[^A-Za-z0-9]/g, '_')
const esc = (s) => String(s).replace(/"/g, '#quot;')
const label = (slug) => bySlug[slug]?.label ?? slug
const cid = (slug) => `c_${id(slug)}`

// ---------- 1. site map ----------
function siteMap() {
  const L = ['flowchart TD']
  L.push(`  home["/ — ${esc(seed.settings.title)}"]`)
  const primary = menus.find((m) => m.name === 'primary')?.items ?? []
  const topbar = menus.find((m) => m.name === 'topbar')?.items ?? []
  const legal = menus.find((m) => m.name === 'footer_legal')?.items ?? []
  const kit = menus.find((m) => m.name === 'resources_kit')?.items ?? []
  const node = (item) => `${id(item.url)}["${esc(item.url)} — ${esc(item.label)}"]`
  L.push('  subgraph primary["Primary menu"]')
  for (const it of primary) if (it.url !== '/') L.push(`    ${node(it)}`)
  L.push('  end')
  L.push('  subgraph topbar["Top bar"]')
  for (const it of topbar) L.push(`    ${node(it)}`)
  L.push('  end')
  L.push('  subgraph footer["Footer · legal"]')
  for (const it of legal) L.push(`    ${node(it)}`)
  L.push('  end')
  L.push('  home --> primary')
  L.push('  home --> topbar')
  L.push('  home --> footer')
  // Detail pages and archives hang under their list page.
  const details = collections.filter((c) => !c.singleton && c.url && c.slug !== 'pages')
  for (const c of details) {
    const parent = c.url.split('/')[1]
    L.push(`  ${id('/' + parent)} --> ${id(c.slug)}_d["${esc(c.url)} — ${esc(c.label)} (${c.count})"]:::gen`)
    for (const t of taxonomies.filter((t) => t.collections.includes(c.slug))) {
      const r = routes.find((r) => r.path.startsWith(`/${parent}/${t.name}/`))
      if (r)
        L.push(
          `  ${id('/' + parent)} --> ${id(c.slug + t.name)}["${esc(r.path)} — by ${esc(t.label)} (${t.terms.length})"]:::gen`
        )
    }
  }
  L.push(`  subgraph tools["Utility pages"]`)
  const inMenus = new Set(menus.flatMap((m) => m.items.map((i) => i.url)))
  for (const r of routes.filter((r) => ['Search', 'Sitemap'].includes(r.view) && !inMenus.has(r.path)))
    L.push(`    ${id(r.path)}["${esc(r.path)}"]`)
  L.push(`    kit["/kit/… — ${kit.map((k) => esc(k.label)).join(' · ')}"]`)
  L.push(`    nf["/404"]`)
  L.push('  end')
  L.push('  home -.-> tools')
  L.push('  classDef gen stroke-dasharray: 4 3')
  return L.join('\n')
}

// ---------- 2. page layout ----------
// The frame is three components around <slot />; which Site chrome fields each one prints is
// read from the component source (`site.<field>`), filtered to fields the schema actually declares.
const siteFieldSlugs = new Set(bySlug.site.fields.map((f) => f.slug))
const siteFieldsOf = (component) =>
  [
    ...new Set(
      [...read(`src/components/site/${component}.astro`).matchAll(/\b(?:site|s)\.([a-z_]+)/g)].map(
        (m) => m[1]
      )
    )
  ].filter((f) => siteFieldSlugs.has(f))
function layout() {
  const top = siteFieldsOf('Topbar')
  const head = siteFieldsOf('Header')
  const foot = siteFieldsOf('Footer')
  const brand = head.filter((f) => f.startsWith('brand_'))
  const actions = head.filter((f) => /^(search|quote)_/.test(f))
  const nav = head.filter((f) => !brand.includes(f) && !actions.includes(f))
  const footerMenus = chrome.menus.filter((m) => m.startsWith('footer_'))
  const L = ['block-beta', '  columns 3']
  L.push(`  topbar["Topbar · menu topbar · ${top.length} site fields"]:3`)
  L.push(`  brand["Brand · ${brand.length} site fields"]`)
  L.push(
    `  nav["Navigation · menu primary · Resources (menu resources_kit, latest ${label('projects')} + ${label('posts')})"]`
  )
  L.push(`  actions["Search · Quote CTA"]`)
  L.push(
    `  main["main — one of ${Object.keys(views).length} views, chosen by the router from the path (diagram 3)"]:3`
  )
  for (const m of footerMenus) L.push(`  ${id(m)}["Footer column · menu ${m}"]`)
  L.push(`  bottom["Footer · ${foot.length} site fields"]:3`)
  const table = [
    '',
    `Every field below lives in **Content › ${esc(label('site'))}**; the menus in **Menus**.`,
    '',
    '| Region | Site chrome fields |',
    '|---|---|',
    `| Topbar | ${top.map((f) => `\`${f}\``).join(', ')} |`,
    `| Brand | ${brand.map((f) => `\`${f}\``).join(', ')} |`,
    `| Navigation | ${nav.map((f) => `\`${f}\``).join(', ')} |`,
    `| Actions | ${actions.map((f) => `\`${f}\``).join(', ')} |`,
    `| Footer | ${foot.map((f) => `\`${f}\``).join(', ')} |`
  ].join('\n')
  return { body: L.join('\n'), after: table }
}

// ---------- 3. where to edit what ----------
function editing() {
  const L = ['flowchart LR']
  const editable = routes.filter(
    (r) =>
      (views[r.view]?.entries ?? []).some((c) => !chromeEntries.has(c)) &&
      !['Search', 'Sitemap'].includes(r.view)
  )
  L.push('  subgraph pages["What you see (public path)"]')
  for (const r of editable) L.push(`    ${id(r.path)}["${esc(r.path)}"]`)
  L.push('  end')
  L.push('  subgraph admin["Where to edit it (Admin)"]')
  for (const c of collections)
    L.push(`    ${cid(c.slug)}["Content › ${esc(c.label)}${c.singleton ? '' : ` (${c.count} entries)`}"]`)
  L.push(`    menus["Menus (${menus.length})"]`)
  L.push('    media["Media library — images and PDFs"]')
  L.push(
    `    forms["Forms plugin — ${[...new Set(formBindings.map((b) => esc(b.form.replace('-{locale}', ''))))].join(' · ')}"]`
  )
  L.push(
    `    i18n["Translations — ${config.locales
      .filter((l) => l !== locale)
      .map((l) => l.toUpperCase())
      .join(', ')} copy of every entry"]`
  )
  L.push('  end')
  for (const r of editable)
    for (const c of views[r.view].entries) if (!chromeEntries.has(c)) L.push(`  ${id(r.path)} --> ${cid(c)}`)
  L.push(`  chrome["Every page: header, footer, contact details"] --> ${cid('site')}`)
  L.push('  chrome --> menus')
  const withImages = collections.filter((c) => c.fields.some((f) => f.type === 'image')).map((c) => c.slug)
  for (const c of withImages) L.push(`  ${cid(c)} -.-> media`)
  for (const b of formBindings) L.push(`  ${cid(b.collection)} -. ${esc(b.field)} .-> forms`)
  L.push('  admin -.-> i18n')
  return L.join('\n')
}

// ---------- 4. content model ----------
function model() {
  const related = new Set([
    ...references.flatMap((r) => [r.from, r.to]),
    ...taxonomies.flatMap((t) => t.collections),
    ...formBindings.map((b) => b.collection)
  ])
  const L = ['erDiagram']
  for (const c of collections.filter((c) => related.has(c.slug))) {
    L.push(`  ${id(c.slug)} {`)
    L.push(
      `    kind ${c.singleton ? 'singleton' : 'list'} "${esc(c.label)}${c.url ? ` · ${esc(c.url)}` : ''}"`
    )
    L.push(`    int fields "${c.fields.length}${c.singleton ? '' : ` · ${c.count} entries`}"`)
    L.push('  }')
  }
  for (const r of references) L.push(`  ${id(r.from)} }o--|| ${id(r.to)} : "${esc(r.field)}"`)
  for (const t of taxonomies) {
    L.push(`  ${id('tax_' + t.name)} {`)
    L.push(`    taxonomy ${t.name} "${esc(t.label)}: ${esc(t.terms.join(', '))}"`)
    L.push('  }')
    for (const c of t.collections) L.push(`  ${id(c)} }o--o{ ${id('tax_' + t.name)} : "${esc(t.name)}"`)
  }
  for (const b of formBindings)
    L.push(
      `  ${id(b.collection)} ||--|| ${id('form_' + b.form.replace('-{locale}', ''))} : "${esc(b.field)}"`
    )
  const alone = collections.filter((c) => !related.has(c.slug))
  const after = [
    '',
    `Not in the picture because nothing points at them and they point at nothing: ${alone
      .map(
        (c) =>
          `**${esc(c.label)}** (${c.singleton ? 'singleton' : `${c.count} entries`}, ${c.fields.length} fields${c.url ? `, \`${c.url}\`` : ''})`
      )
      .join(', ')}. Each is a self-contained page: its copy, images and repeaters are all its own fields.`
  ].join('\n')
  return { body: L.join('\n'), after }
}

// ---------- 5. flows ----------
function submitFlow() {
  const quote = formBindings.find((b) => b.collection === 'contact')
  const L = ['sequenceDiagram', '  autonumber']
  L.push('  actor V as Visitor')
  L.push(`  participant S as Site (${esc(bySlug.contact?.url ?? '/contact')})`)
  L.push('  participant F as Forms plugin')
  L.push('  participant M as emdash-smtp')
  L.push('  participant X as SMTP server')
  L.push('  participant A as Admin')
  L.push(`  V->>S: fill "${esc(quote?.form.replace('-{locale}', '') ?? 'contact')}" and submit`)
  L.push('  S->>F: POST submission')
  L.push('  F-->>S: stored (Admin › Forms › Submissions)')
  L.push('  F->>M: notify')
  L.push(`  M->>X: mail from ${esc(config.mail.fromEmail)}`)
  L.push(`  X-->>A: notification to ${esc(config.mail.notifyTest)}`)
  L.push('  S-->>V: thank-you state')
  return L.join('\n')
}
function publishFlow() {
  const others = config.locales.filter((l) => l !== locale).map((l) => l.toUpperCase())
  const L = ['stateDiagram-v2']
  L.push(`  [*] --> Draft : editor saves (${locale.toUpperCase()})`)
  L.push('  Draft --> Draft : Save again')
  L.push('  Draft --> Published : Publish changes → Publish changes now')
  L.push('  Published --> Draft : edit again (public page keeps the published version)')
  for (const o of others) L.push(`  Published --> Translated_${o} : Translations › Edit ${o}`)
  for (const o of others) L.push(`  Translated_${o} --> Published : publish the ${o} copy`)
  L.push('  Published --> [*]')
  return L.join('\n')
}

// ---------- assemble ----------
const fence = (title, why, d) => {
  const { body, after } = typeof d === 'string' ? { body: d, after: '' } : d
  return `### ${title}\n\n${why}\n\n\`\`\`mermaid\n${body}\n\`\`\`\n${after ? `${after}\n` : ''}`
}
const block = [
  START,
  '',
  '## Site at a glance',
  '',
  `Five diagrams for whoever administers a site built from this template. They are generated from \`seed/seed.json\`, \`template.config.json\`, the router and the views by \`node tools/diagrams.mjs\` (\`--check\` in CI), so they describe the template as it is — regenerate after changing the schema, menus, routes or forms. Paths are shown for \`${locale}\`; every other locale (${config.locales
    .filter((l) => l !== locale)
    .map((l) => `\`/${l}\``)
    .join(', ')}) mirrors the same tree.`,
  '',
  fence(
    '1. Site map',
    `Which pages exist and how they hang together. Dashed nodes are generated from content (one page per entry or per term); the count is what the seed ships.`,
    siteMap()
  ),
  fence(
    '2. Page layout',
    `Every page is the same frame around one view. The frame reads the **${esc(label('site'))}** entry and the menus; the view reads its own collection (diagram 3).`,
    layout()
  ),
  fence(
    '3. Where to edit what',
    `Start from the page you are looking at; the arrow ends on the admin screen that holds its copy. Dotted arrows: images come from the media library, the two forms are wired by id, and each entry has a translation per locale.`,
    editing()
  ),
  fence(
    '4. Content model',
    `Singletons hold a page's copy; lists hold entries with a slug. Crow's-foot lines are references (a home-page slot points at a project), taxonomies (a post has categories and tags) and the form bindings.`,
    model()
  ),
  fence(
    '5a. What happens when a visitor submits the quote form',
    `Where a submission is stored and who gets mailed. SMTP is configured with \`tools/configure-smtp.mjs\`.`,
    submitFlow()
  ),
  fence(
    '5b. Life of an edit',
    `Saving never touches the public site; publishing does. Translations are separate copies with their own publish step.`,
    publishFlow()
  ),
  END
].join('\n')

const readmePath = path.join(root, 'README.md')
if (!existsSync(readmePath)) throw new Error('README.md not found; run from the template package root')
const readme = read('README.md')
const s = readme.indexOf(START)
const e = readme.indexOf(END)
let next
if (s >= 0 && e > s) next = readme.slice(0, s) + block + readme.slice(e + END.length)
else {
  // First run: the section goes right before "## Where things live", the map of the repo.
  const anchor = '\n## Where things live'
  const i = readme.indexOf(anchor)
  if (i < 0) throw new Error('README.md has neither the diagram markers nor "## Where things live"')
  next = readme.slice(0, i) + '\n' + block + '\n' + readme.slice(i)
}
if (check) {
  if (next !== readme) {
    console.error('README.md diagrams are stale: run node tools/diagrams.mjs')
    process.exit(1)
  }
  console.log('README.md diagrams are current')
} else {
  writeFileSync(readmePath, next)
  console.log(
    `README.md: diagrams written (${routes.length} routes, ${collections.length} collections, ${taxonomies.length} taxonomies, ${menus.length} menus)`
  )
}
