/**
 * One preset, read closely — its `preset-<id>` row in `presets.patch.yml` and what it gives an agent.
 *
 * WHY THIS SCREEN IS READ-ONLY AND THE OTHER ONE IS NOT. The boundary is not "internal surfaces
 * are read-only"; it is source versus generated. `config/mode-matrix.json` is what people write, and
 * the CMS agents screen edits it. The files shown here are what `scripts/gen-presets.ts` writes
 * out of that matrix — editing them by hand makes the two disagree, silently, until the next
 * generator run quietly throws the edit away.
 *
 * WHY BOTH THE READING AND THE FILE. A reading answers "does this agent have bash" in a second but
 * is an interpretation, and interpretations drift. The file never drifts but makes a person read
 * YAML to answer the same question. So: the reading is the front, the file is one tab away, and
 * the tab is labelled with the FILE NAME — that label is what tells a reader the left-hand side is
 * a reading *of* something.
 */
import { Badge, Button, Card, Separator, Tabs, TabsContent, TabsList, TabsTrigger } from '@tracy/ui'
import { ExternalLink, FileCode2, Layers, MessageSquareText, Wrench } from 'lucide-react'
import { useT } from './i18n'
import {
  overlays,
  type PlatformId,
  packageOf,
  personas,
  platforms,
  type RoleId,
  resolve,
  roleLabel,
  roles
} from './matrix'
import { RowList } from './RowList'

const REPO = 'https://github.com/TracyHQ/tch/blob/main'
/** Since dsh 0.1.7 every preset is one `preset-<id>` row in this generated file, not a folder. */
const PRESETS_FILE = 'packages/bundle/tracy-cowork/presets.patch.yml'
const PRESETS_FILE_NAME = 'presets.patch.yml'
/** Where the persona and the skill folder sit in that file: identifiers, the same in every language. */
const PERSONA_PATH = 'entries[id=persona].config.text'
const SKILL_DIRS_KEY = 'customSkillDirs'
const SKILL_DIR = '/opt/tracy/skills'

/**
 * The file as the generator writes it.
 *
 * REBUILT HERE RATHER THAN FETCHED, and that is a deliberate limit worth naming: the Worker serves
 * static assets and has no repository to read from, so this is the same composition rule the
 * generator follows, applied to the same matrix. If the two ever disagree, the `presets` gate
 * fails in CI before anyone sees this screen — that gate is what makes rebuilding safe.
 */
export function presetYaml(role: RoleId, platform: PlatformId) {
  const { tools } = resolve(role, platform)
  const persona = [personas[role]?.trim(), overlays[platform]?.persona?.trim()].filter(Boolean).join('\n\n')

  const lines = [
    '# Generated by scripts/gen-presets.ts from config/mode-matrix.json. Do not edit by hand:',
    '# edit the matrix and re-run, or the two drift with nothing to notice.',
    ''
  ]
  for (const row of tools) {
    const pkg = packageOf(row.id)
    if (!pkg) continue
    lines.push(`- id: ${row.id}`, `  name: '${pkg}'`)
    if (row.id === 'persona' && persona) {
      lines.push('  config:', '    text: >-', ...persona.split('\n').map((l) => `      ${l}`))
    }
    if (row.id === 'skill-filesystem') {
      lines.push('  config:', `    ${SKILL_DIRS_KEY}:`, `      - ${SKILL_DIR}`)
    }
  }
  return `${lines.join('\n')}\n`
}

export function Preset({
  role,
  platform,
  onBack
}: {
  role: RoleId
  platform: PlatformId
  onBack: () => void
}) {
  const t = useT()
  const { tools, skills } = resolve(role, platform)
  const roleRow = roles.find((r) => r.id === role)
  const persona = personas[role]?.trim()
  const id = `${role}-${platform}`
  const row = `preset-${id}`

  return (
    <div className="flex w-full flex-col gap-4 px-6 py-6">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div className="min-w-0">
          <div className="flex flex-wrap items-center gap-2">
            <h1 className="font-semibold text-lg tracking-tight">
              {t('matrix.preset.title', {
                role: roleRow ? roleLabel(roleRow, t) : role,
                platform: platforms.find((p) => p.id === platform)?.label ?? platform
              })}
            </h1>
            <Badge variant="outline" className="font-mono">
              {id}
            </Badge>
            {/* Here, and not on the app shell. The other screen is editable, and a badge at the
                top level would have said otherwise about both. */}
            <Badge variant="secondary">{t('matrix.preset.readOnlyGenerated')}</Badge>
          </div>
          <p className="mt-1 text-muted-foreground text-sm">{t('matrix.preset.lead')}</p>
        </div>
        <div className="flex flex-none gap-2">
          <Button variant="ghost" size="sm" onClick={onBack}>
            {t('matrix.preset.back')}
          </Button>
          <Button
            variant="outline"
            size="sm"
            // A link wearing a button's clothes: without this base-ui expects a native <button> and

            // warns in the console on every render.

            nativeButton={false}
            render={<a href={`${REPO}/${PRESETS_FILE}`} target="_blank" rel="noreferrer" />}
          >
            <ExternalLink />
            {t('matrix.preset.openGithub')}
          </Button>
        </div>
      </div>

      <Tabs defaultValue="reading" className="gap-3">
        <TabsList>
          <TabsTrigger value="reading">
            <Layers />
            {t('matrix.preset.tabReading')}
          </TabsTrigger>
          <TabsTrigger value="cordis">
            <FileCode2 />
            {PRESETS_FILE_NAME}
          </TabsTrigger>
        </TabsList>

        <TabsContent value="reading">
          <div className="flex flex-col gap-4">
            <Card className="gap-0 px-5 py-4">
              <div className="flex flex-wrap items-center gap-2">
                <MessageSquareText className="size-4 text-muted-foreground" />
                <h2 className="font-medium text-sm">{t('matrix.preset.persona')}</h2>
                <Badge variant="outline" className="font-normal">
                  {t('matrix.preset.inEveryPrompt')}
                </Badge>
                <span className="ms-auto font-mono text-muted-foreground text-xs">{PERSONA_PATH}</span>
              </div>
              {persona ? (
                <p className="mt-2 whitespace-pre-wrap rounded-lg bg-muted px-3 py-2 font-mono text-xs">
                  {persona}
                </p>
              ) : (
                <p className="mt-2 rounded-lg border border-border border-dashed px-3 py-6 text-center text-muted-foreground text-xs">
                  {t('matrix.preset.noPersona')}
                </p>
              )}
            </Card>

            <RowList
              title={t('matrix.preset.tools')}
              icon={<Wrench />}
              rows={tools}
              kind="tool"
              platform={platform}
            />

            <Card className="gap-0 px-5 py-4">
              <div className="flex flex-wrap items-center gap-2">
                <Layers className="size-4 text-muted-foreground" />
                <h2 className="font-medium text-sm">{t('matrix.preset.skills')}</h2>
                <span className="text-muted-foreground text-xs tabular-nums">{skills.length}</span>
                <span className="ms-auto font-mono text-muted-foreground text-xs">{SKILL_DIRS_KEY}</span>
              </div>
              {/* One line, because that is what the YAML says: a directory. The count above is what
                  the directory holds today, which is a different fact. */}
              <p className="mt-2 font-mono text-muted-foreground text-xs">{SKILL_DIR}</p>
              <p className="mt-1 text-muted-foreground text-xs">{t('matrix.preset.skillsNote')}</p>
            </Card>
          </div>
        </TabsContent>

        <TabsContent value="cordis">
          <Card className="gap-0 overflow-hidden py-0">
            <div className="flex flex-wrap items-center gap-2 px-4 py-2.5">
              <FileCode2 className="size-3.5 flex-none text-muted-foreground" />
              <span className="min-w-0 truncate font-mono text-xs">
                {PRESETS_FILE} · {row}
              </span>
              <Badge variant="secondary" className="ms-auto flex-none font-normal">
                {t('matrix.preset.readOnly')}
              </Badge>
              <Button
                variant="ghost"
                size="sm"
                // A link wearing a button's clothes: without this base-ui expects a native <button> and

                // warns in the console on every render.

                nativeButton={false}
                render={<a href={`${REPO}/${PRESETS_FILE}`} target="_blank" rel="noreferrer" />}
              >
                <ExternalLink />
                {t('matrix.preset.editGithub')}
              </Button>
            </div>
            <Separator />
            <pre className="overflow-x-auto px-4 py-3 font-mono text-xs leading-relaxed">
              {presetYaml(role, platform)}
            </pre>
          </Card>
        </TabsContent>
      </Tabs>
    </div>
  )
}
