/**
 * `content.find` against a real directory tree.
 *
 * WHAT THESE GUARD, and why they are worth a temp directory rather than a stub: the three decisions
 * that make this better than the `grep -rn` it replaces are all decisions the walk makes, not the
 * pure helpers — filter a language hit on its VALUE, say when a key is ALREADY overridden, and never
 * let an admin override speak for a page a visitor sees. Each of those fails silently: the answer
 * still looks like an answer.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'

import { contentFind } from '../src/host/find.mjs'

/** A Joomla webroot with the four files the measured sessions actually grepped. */
function joomlaSite(files = {}) {
  const root = mkdtempSync(path.join(tmpdir(), 'content-find-'))
  const web = path.join(root, 'demo', '.webroot')
  const all = {
    'administrator/index.php': '<?php',
    'language/en-GB/com_users.ini': 'COM_USERS_LOGIN_HOME="Dashboard"\nCOM_USERS_LOGIN_PASSWORD="Password"\n',
    'language/en-GB/mod_breadcrumbs.ini':
      'MOD_BREADCRUMBS_HOME="Home"\nMOD_BREADCRUMBS_YOU_ARE_HERE="You are here:"\n',
    'modules/mod_login/tmpl/default.php': '<?php echo Text::_("MOD_LOGIN_VALUE_PASSWORD"); ?>',
    ...files
  }
  for (const [rel, body] of Object.entries(all)) {
    mkdirSync(path.join(web, path.dirname(rel)), { recursive: true })
    writeFileSync(path.join(web, rel), body)
  }
  return root
}

const asJoomla = async () => 'joomla'

test('a language hit is filtered on its VALUE, so a key that merely spells the word is not returned', async () => {
  // `COM_USERS_LOGIN_HOME="Dashboard"` is what `grep -rn Home language/en-GB/*.ini` returns and the
  // agent then reads. It is not a hit: no visitor reads a key name.
  const found = await contentFind(joomlaSite(), 'demo', { text: 'Home' }, asJoomla)
  assert.equal(found.ok, true)
  assert.equal(found.matches.length, 1)
  assert.equal(found.matches[0].key, 'MOD_BREADCRUMBS_HOME')
  assert.equal(found.matches[0].value, 'Home')
  assert.equal(found.matches[0].layer, 'PHRASES')
})

test('a hit in a shipped file sends the agent to the override directory, never to that file', async () => {
  const found = await contentFind(joomlaSite(), 'demo', { text: 'Password' }, asJoomla)
  const shipped = found.matches.find((m) => m.file.endsWith('com_users.ini'))
  assert.match(shipped.door, /language\/overrides\//)
  assert.match(shipped.door, /never edit this shipped file/)
})

test('a key this site ALREADY overrides is said so, with the value in force', async () => {
  // The shape that broke a real request: once one phrase is translated, the override holds the NEW
  // words, so searching the old ones finds only the shipped line — and a second change is proposed
  // that the existing override still wins over.
  const root = joomlaSite({ 'language/overrides/en-GB.override.ini': 'MOD_BREADCRUMBS_HOME="Trang chủ"\n' })
  const found = await contentFind(root, 'demo', { text: 'Home' }, asJoomla)
  const hit = found.matches[0]
  assert.deepEqual(hit.overriddenBy, {
    file: '.webroot/language/overrides/en-GB.override.ini',
    line: 1,
    value: 'Trang chủ'
  })
  assert.match(hit.door, /ALREADY overridden/)
  assert.match(hit.door, /change that line, not the shipped one/)
})

test('an admin override never speaks for a page a visitor sees', async () => {
  // Joomla keeps separate site and admin override files and one key can live in both.
  const root = joomlaSite({
    'administrator/language/overrides/en-GB.override.ini': 'MOD_BREADCRUMBS_HOME="Admin only"\n'
  })
  const found = await contentFind(root, 'demo', { text: 'Home' }, asJoomla)
  const hit = found.matches.find((m) => m.side === 'site')
  assert.equal(hit.overriddenBy, undefined)
})

test('the extension that renders a string is not offered as a file to edit', async () => {
  const found = await contentFind(joomlaSite(), 'demo', { text: 'MOD_LOGIN_VALUE_PASSWORD' }, asJoomla)
  const tmpl = found.matches.find((m) => m.file.endsWith('default.php'))
  assert.equal(tmpl.layer, 'PHRASES')
  assert.match(tmpl.door, /do not edit this file/)
})

test('every answer says what it did NOT search, including a full one', async () => {
  // "No matches" without this reads as "this word is nowhere on the site" — the conclusion that sent
  // one measured session to rename a template. Most visible words are database records.
  for (const text of ['Home', 'a phrase that is nowhere']) {
    const found = await contentFind(joomlaSite(), 'demo', { text }, asJoomla)
    assert.match(found.notSearched, /Only files were searched/)
    assert.match(found.notSearched, /content\.list/)
    assert.ok(Array.isArray(found.searched) && found.searched.length > 0)
  }
})

test('a platform that keeps no words in files refuses, and names a door that works there', async () => {
  const root = mkdtempSync(path.join(tmpdir(), 'content-find-'))
  mkdirSync(path.join(root, 'em', '.tracy'), { recursive: true })
  writeFileSync(
    path.join(root, 'em', '.tracy', 'site.json'),
    '{"siteKey":"em.tracy.test","platform":"emdash"}'
  )
  // The declared platform is read BEFORE the webroot is sniffed: an EmDash `.webroot/` holds data
  // and uploads, not a CMS marker, so sniffing alone calls it `unknown` and the refusal would point
  // at a door that refuses on that platform. (It HAS a `.webroot/` — see find.mjs for why the
  // distinction matters.)
  const found = await contentFind(root, 'em', { text: 'Home' }, async () => 'unknown')
  assert.equal(found.ok, false)
  assert.equal(found.code, 'NO_FILE_LAYERS')
  assert.match(found.next, /tracy_emdash/)
})

test('an empty or oversized phrase is refused rather than walked', async () => {
  const root = joomlaSite()
  assert.equal((await contentFind(root, 'demo', {}, asJoomla)).code, 'BAD_TEXT')
  assert.equal((await contentFind(root, 'demo', { text: '   ' }, asJoomla)).code, 'BAD_TEXT')
  assert.equal((await contentFind(root, 'demo', { text: 'x'.repeat(201) }, asJoomla)).code, 'BAD_TEXT')
})

test('a conversation standing in no site is told so, not handed an empty result', async () => {
  const found = await contentFind(joomlaSite(), null, { text: 'Home' }, asJoomla)
  assert.equal(found.ok, false)
  assert.equal(found.code, 'NO_SITE_IN_CONVERSATION')
})

/** A quickstart site: a contract marker under `.content-contracts/`, and a template file. */
function quickstartSite(platform) {
  const root = mkdtempSync(path.join(tmpdir(), 'content-find-'))
  mkdirSync(path.join(root, 'shop', '.webroot', 'templates', 'tpl'), { recursive: true })
  mkdirSync(path.join(root, 'shop', '.tracy'), { recursive: true })
  writeFileSync(path.join(root, 'shop', '.tracy', 'site.json'), JSON.stringify({ platform }))
  writeFileSync(
    path.join(root, 'shop', '.webroot', 'templates', 'tpl', 'index.php'),
    '<p>Get a free quote</p>'
  )
  mkdirSync(path.join(root, '.content-contracts'), { recursive: true })
  writeFileSync(path.join(root, '.content-contracts', 'shop.json'), '{"contract":"tracy-business"}')
  return root
}

// ADR 0022 (26/09/2026): a quickstart site's files are open; the contract marker refuses nothing.
test('a quickstart site is searched like any other: the marker is no refusal', async () => {
  const found = /** @type {any} */ (
    await contentFind(quickstartSite('joomla'), 'shop', { text: 'Get a free quote' }, async () => 'joomla')
  )
  assert.notEqual(found.code, 'CONTENT_CONTRACT')
})

test('an EmDash site is sent to its words road, never to "{list: true}" first (D29)', async () => {
  const root = mkdtempSync(path.join(tmpdir(), 'content-find-'))
  mkdirSync(path.join(root, 'em', '.tracy'), { recursive: true })
  writeFileSync(path.join(root, 'em', '.tracy', 'site.json'), '{"platform":"emdash"}')
  const found = /** @type {any} */ (await contentFind(root, 'em', { text: 'Home' }, async () => 'unknown'))
  assert.doesNotMatch(found.next, /list: ?true/)
  assert.match(found.next, /content_get \{collection, id:"<slug>"\}/)
})

test('a walk cut by its file budget says so, never "search a longer phrase"; one cut by matches still does', async () => {
  // 16/10/2026, Joomla: 4000 files opened, no match, and the answer said "more matches than fit one
  // answer — search a longer phrase", so the model searched again with a longer phrase.
  const many = Object.fromEntries(
    Array.from({ length: 4001 }, (_, i) => [`language/en-GB/mod_x${i}.ini`, `MOD_X${i}="Nothing here"\n`])
  )
  const wide = await contentFind(joomlaSite(many), 'demo', { text: 'Elena Gurova' }, asJoomla)
  assert.equal(wide.matches.length, 0)
  assert.doesNotMatch(wide.stopped, /search a longer phrase/)
  assert.match(wide.stopped, /part of the site unsearched/)

  const noisy = Object.fromEntries(
    Array.from({ length: 60 }, (_, i) => [`language/en-GB/mod_y${i}.ini`, `MOD_Y${i}="Opening hours"\n`])
  )
  const full = await contentFind(joomlaSite(noisy), 'demo', { text: 'Opening hours' }, asJoomla)
  assert.match(full.stopped, /search a longer phrase/)
})
