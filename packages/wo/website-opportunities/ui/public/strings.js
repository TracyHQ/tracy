/** The text of `key` with `{name}` filled from `params`; the key itself when it is missing, so a gap is visible. */
export function t(key, params = {}) {
  const text = STRINGS[key] ?? key
  return text.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole))
}

/** `<base>.one` or `<base>.other` by `count`. */
export function tCount(base, count, params = {}) {
  return t(`${base}.${count === 1 ? 'one' : 'other'}`, { count, ...params })
}
