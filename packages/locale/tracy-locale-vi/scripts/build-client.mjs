#!/usr/bin/env node
/**
 * Bundles `vi/*.json` into `lib/client.js` — what dsh serves at `/plugins/@tracy/dsh-tracy-locale-vi/client.js`.
 *
 * WHY GENERATED, NOT HAND-WRITTEN. Translations must live as **data**, not code: `pnpm lang:check`
 * scans every string in `packages/` and Vietnamese in a `.js` file is a violation — as that script
 * itself advises, "data goes into a data file, do not embed it in code". JSON also diffs better: one
 * line per key.
 *
 * `lib/client.js` is COMMITTED, not gitignored: the fleet copies the plugin folder as-is into
 * `$DESK_HOME/profiles/node_modules/` and runs no build step there.
 *
 * BOUNDARY (settled 2026-08-30): this package translates only Tracy's OWN namespaces. dsh's own
 * namespaces belong to the community `dsh-locale-vi`, which also OWNS the `vi` language — it is the
 * only place that calls `addLanguage`. Calling it again here is a duplicate id and crashes the plugin
 * tree.
 *
 * Comments inside the template below must be in English: they go straight into `lib/client.js`, and
 * `pnpm lang:check` sees the whole template literal as ONE string, so an allowlist cannot help.
 *
 * `--check` writes nothing and exits non-zero only when the bundle has drifted from its source. It is
 * in `pnpm build:check` because a stale bundle fails silently: fix a translation, forget to rebuild,
 * and the fleet still gets the old words.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const SOURCE_DIR = path.join(ROOT, 'vi')
const BUNDLE = path.join(ROOT, 'lib/client.js')

const namespaces = readdirSync(SOURCE_DIR)
  .filter((file) => file.endsWith('.json'))
  .sort()
  .map((file) => {
    const ns = file.slice(0, -'.json'.length)
    const entries = JSON.parse(readFileSync(path.join(SOURCE_DIR, file), 'utf8'))
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== 'string') {
        console.error(`build-client: vi/${file} key "${key}" is not a string — dictionaries are flat.`)
        process.exit(1)
      }
    }
    return { ns, entries }
  })

if (namespaces.length === 0) {
  console.error(`build-client: no dictionaries found in ${SOURCE_DIR}`)
  process.exit(1)
}

const dictionaries = namespaces
  .map(
    ({ ns, entries }) =>
      `      ${JSON.stringify(ns)}: ${JSON.stringify(entries, null, 8).replace(/\n/g, '\n      ')}`
  )
  .join(',\n')

const bundle = `window.__ModuleLoader__.load({
  id: '@tracy/dsh-tracy-locale-vi',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })

    /**
     * GENERATED by scripts/build-client.mjs from vi/*.json — do not edit by hand.
     * Run \`node scripts/build-client.mjs\` after changing a dictionary.
     */
    const VI = {
${dictionaries}
    }

    /** Required service: the dictionary registry the locale plugin provides. */
    const inject = ['locale']

    /**
     * Register the Vietnamese half of Tracy's OWN namespaces.
     *
     * NO addLanguage() here: \`dsh-locale-vi\` owns the \`vi\` language definition and every
     * namespace dsh itself ships. A second call on the same id throws at registration and
     * takes the whole plugin tree down.
     *
     * register() throws on a duplicate (namespace, locale), so exactly one package registers
     * one namespace for one language. One effect per namespace, never nested: a namespace
     * whose owning plugin is disabled must not take the others down with it.
     */
    function apply(ctx) {
      for (const ns of Object.keys(VI)) {
        ctx.effect(() => ctx.locale.register(ns, 'vi', VI[ns]), 'tracy-locale: ' + ns)
      }
    }

    exports.apply = apply
    exports.inject = inject
    return module.exports
  }
})
`

const entryCount = namespaces.reduce((sum, { entries }) => sum + Object.keys(entries).length, 0)

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(BUNDLE, 'utf8')
  } catch {
    console.error('build-client: lib/client.js is missing — run `node scripts/build-client.mjs`.')
    process.exit(1)
  }
  if (current !== bundle) {
    console.error(
      'build-client: lib/client.js is stale — a dictionary changed but the bundle was not rebuilt.\n' +
        '  Run `pnpm --filter @tracy/dsh-tracy-locale-vi build`.'
    )
    process.exit(1)
  }
  console.log(`build-client: bundle matches ${namespaces.length} dictionaries (${entryCount} entries).`)
  process.exit(0)
}

writeFileSync(BUNDLE, bundle)
console.log(`build-client: wrote lib/client.js — ${namespaces.length} namespaces, ${entryCount} entries.`)
