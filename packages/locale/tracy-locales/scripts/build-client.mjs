#!/usr/bin/env node
/**
 * Bundle `<lang>/*.json` into `lib/client.js`, the file dsh serves at
 * `/plugins/@tracy/dsh-tracy-locales/client.js` (spec #730).
 *
 * Same model as `packages/locale/tracy-locale-vi/scripts/build-client.mjs`: translations are DATA
 * (one key per line, reviewable diffs), the bundle is generated and COMMITTED because the image
 * copies the plugin folder as-is and runs no build (CLAUDE.md law #3).
 *
 * One directory per language. A file `<lang>/<ns>.json` registers namespace `<ns>` for `<lang>`.
 * `languages.json` lists the languages this package OWNS and therefore adds with `addLanguage`
 * (es, ticket #739): nobody else ships them. de/fr/it/nl are added by better-locale and zh by dsh,
 * so they must never appear there (a second `addLanguage` on an id throws and takes dsh down).
 * It may register a dsh namespace only where no other package registers it for that language;
 * `scripts/check-interface-languages.ts` fails otherwise (a duplicate register throws in dsh).
 *
 * `--check` writes nothing and exits non-zero when the bundle no longer matches the sources.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const BUNDLE = path.join(ROOT, 'lib/client.js')
const LANGUAGE_DIR = /^[a-z]{2}(?:-[A-Za-z0-9]+)?$/
const OWNED = JSON.parse(readFileSync(path.join(ROOT, 'languages.json'), 'utf8'))
for (const language of OWNED) {
  if (typeof language.id !== 'string' || typeof language.label !== 'string' || language.fallback !== 'en') {
    console.error(
      `build-client: languages.json entry ${JSON.stringify(language)} needs id, label and fallback "en".`
    )
    process.exit(1)
  }
}

const languages = readdirSync(ROOT)
  .filter((name) => LANGUAGE_DIR.test(name) && statSync(path.join(ROOT, name)).isDirectory())
  .sort()

const table = {}
let entryCount = 0
for (const lang of languages) {
  const dir = path.join(ROOT, lang)
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()) {
    const ns = file.slice(0, -'.json'.length)
    const entries = JSON.parse(readFileSync(path.join(dir, file), 'utf8'))
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== 'string') {
        console.error(`build-client: ${lang}/${file} key "${key}" is not a string — dictionaries are flat.`)
        process.exit(1)
      }
    }
    table[lang] ??= {}
    table[lang][ns] = entries
    entryCount += Object.keys(entries).length
  }
}

if (languages.length === 0) {
  console.error(`build-client: no language directories found in ${ROOT}`)
  process.exit(1)
}

const body = JSON.stringify(table, null, 2).replace(/\n/g, '\n    ')

const bundle = `window.__ModuleLoader__.load({
  id: '@tracy/dsh-tracy-locales',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })

    /**
     * GENERATED by scripts/build-client.mjs from <lang>/*.json — do not edit by hand.
     * Run \`node scripts/build-client.mjs\` after changing a dictionary.
     */
    const DICTIONARIES = ${body}

    /** Languages this package owns and adds (languages.json). */
    const OWNED_LANGUAGES = ${JSON.stringify(OWNED)}

    /** Required service: the dictionary registry the locale plugin provides. */
    const inject = ['locale']

    /**
     * Add the languages this package owns, then register every (namespace, language) dictionary.
     * Only OWNED_LANGUAGES are added: de, fr, it, nl belong to better-locale and zh to dsh.
     * register() throws on a duplicate (namespace, locale), so exactly one package registers one
     * pair. One effect per pair, never nested: a pair whose namespace owner is disabled must not
     * take others down.
     */
    function apply(ctx) {
      for (const language of OWNED_LANGUAGES) {
        ctx.effect(() => ctx.locale.addLanguage(language), 'tracy-locales: language ' + language.id)
      }
      for (const lang of Object.keys(DICTIONARIES)) {
        for (const ns of Object.keys(DICTIONARIES[lang])) {
          ctx.effect(() => ctx.locale.register(ns, lang, DICTIONARIES[lang][ns]), 'tracy-locales: ' + lang + ' ' + ns)
        }
      }
    }

    exports.apply = apply
    exports.inject = inject
    return module.exports
  }
})
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(BUNDLE, 'utf8')
  } catch {
    console.error('build-client: lib/client.js is missing — run `node scripts/build-client.mjs`.')
    process.exit(1)
  }
  if (current !== bundle) {
    console.error(
      'build-client: lib/client.js is stale — a dictionary changed but the bundle was not rebuilt.\n' +
        '  Run `pnpm --filter @tracy/dsh-tracy-locales build`.'
    )
    process.exit(1)
  }
  console.log(`build-client: bundle matches ${languages.length} languages (${entryCount} entries).`)
  process.exit(0)
}

writeFileSync(BUNDLE, bundle)
console.log(`build-client: wrote lib/client.js — ${languages.length} languages, ${entryCount} entries.`)
