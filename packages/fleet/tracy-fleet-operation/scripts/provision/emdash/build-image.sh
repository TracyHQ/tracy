#!/usr/bin/env bash
# Build the EmDash image for this fleet host, from the open-source upstream.
#
# EmDash is a third-party project — https://github.com/emdash-cms/emdash — and the `Dockerfile` at
# that repo's root is what builds the image. Tracy does not fork or patch it: this script only
# clones a tag and builds.
#
# 🔒 ALWAYS THE LATEST VERSION, and that is SAFE HERE in a way it would not be for an existing site:
# an EmDash site is always a fresh install (`PLATFORM_NEEDS_WEBROOT=0`, `PLATFORM_NEEDS_DB=0` — no
# import path, confirmed 29/08). No old data has to survive an upgrade, so "latest at image build
# time" is exactly what a newly created site should run.
#
# 🔒 BUILD ON THE SERVER, NOT ON A PERSONAL MACHINE. The monorepo needs ~15 GB of scratch, and Docker
# on a desktop Mac died with OOM/ENOSPC — a trap already hit, written up in
# `tracy-docs/fleet/playbook-them-platform-vao-create-a-new-site.md`.
#
#   bash /opt/tracy-fleet/provision/emdash/build-image.sh            # latest upstream version
#   bash /opt/tracy-fleet/provision/emdash/build-image.sh 0.34.0     # a specific version
#
# The image is tagged with its EXACT VERSION, never `latest`: a floating tag makes "which version is
# this site running" unanswerable, and that is the first question on-call asks when a site breaks.
set -euo pipefail

UPSTREAM="${EMDASH_UPSTREAM:-https://github.com/emdash-cms/emdash.git}"
WANT="${1:-}"

if [ -z "$WANT" ]; then
  echo "==> asking upstream for the latest version"
  # The app's OWN tag is `emdash@<version>`. The monorepo has ~11 other prefixes
  # (`@emdash-cms/admin@…`, `create-emdash@…`) — a wrong filter builds the wrong thing.
  # Releases only (`x.y.z`): `sort -V` orders `1.0.1-rc.1` AFTER `1.0.1`, so unfiltered it picked
  # the release candidate on 28/09 (test/emdash-build-image.test.mjs).
  WANT="$(git ls-remote --tags "$UPSTREAM" 2>/dev/null \
    | awk '{print $2}' | sed 's|refs/tags/||' | grep -v '\^{}' \
    | grep -E '^emdash@[0-9]+\.[0-9]+\.[0-9]+$' | sed 's/^emdash@//' | sort -V | tail -1)"
  [ -n "$WANT" ] || { echo "!! could not read any tag from $UPSTREAM" >&2; exit 1; }
fi
TAG="emdash@$WANT"
IMAGE="tracy/emdash:$WANT"
echo "==> $TAG  →  $IMAGE"

if docker image inspect "$IMAGE" >/dev/null 2>&1; then
  echo "==> $IMAGE is already here — not building it again"
  exit 0
fi

# Shallow clone of exactly one tag. The monorepo is ~475k lines of TS; `--depth 1` is the difference
# between a few tens of MB and a few hundred.
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
echo "==> clone $TAG"
git clone --depth 1 --branch "$TAG" "$UPSTREAM" "$WORK/emdash" 2>&1 | tail -2

[ -f "$WORK/emdash/Dockerfile" ] || { echo "!! upstream has no Dockerfile at its root — build by hand" >&2; exit 1; }

# 🔒 REINSTALL AFTER `COPY . .` — patched into the CLONE, not into upstream.
#
# EmDash's Dockerfile contradicts itself in the build stage:
#
#   30  sed -i '/slidev/d' pnpm-workspace.yaml   ← drops a workspace
#   31  pnpm install --frozen-lockfile           ← installs the tree WITH it dropped
#   36  COPY . .                                 ← copies the ORIGINAL tree over it, plus full docs/ and e2e/
#   40  pnpm build                               ← pnpm sees a different tree than at install → refuses to run
#
# pnpm is right, and it even says how to fix it: `Run "pnpm install"`. That is the line added here.
# Cheap, because `node_modules` from the `deps` stage is intact — this install only re-checks the
# workspace tree and downloads no package again.
#
# WHY IT ONLY BROKE NOW, though the Dockerfile has not changed since 20/07: line 3 runs `corepack
# prepare pnpm@10.28.0` but `package.json` declares `packageManager: pnpm@11.x`, and corepack follows
# `package.json`. What actually runs is **the latest pnpm 11 at build time** — the log of the failed
# run on 29/08 has both `pnpm@10.28.0` and `pnpm@11.24.0`. This build is NOT REPRODUCIBLE: the 0.34.0
# image built 23/08 works, the very same commit rebuilt today dies. Same machine, same code,
# different day.
#
# Two approaches tried and rejected: pinning `packageManager` to 10.28.0 →
# `ERR_PNPM_LOCKFILE_CONFIG_MISMATCH` (the lockfile was generated by pnpm 11, upstream's `prepare`
# line is stale); setting `npm_config_verify_deps_before_run=false` → pnpm does not read that knob
# from env.
sed -i 's|^RUN pnpm build |RUN pnpm install --frozen-lockfile \&\& pnpm build |' "$WORK/emdash/Dockerfile"
grep -q '^RUN pnpm install --frozen-lockfile && pnpm build' "$WORK/emdash/Dockerfile" \
  || { echo "!! could not insert the patch — the upstream Dockerfile changed, read it again" >&2; exit 1; }
echo "==> adding a reinstall after the COPY (repairs a workspace tree that drifted)"

# 🔒 Node's heap, not the machine's RAM. The `pnpm deploy --legacy` step bundles the whole blog
# template into a standalone tree and dies at `Reached heap limit` (exit 134) with the default heap.
# The host has 11 GB, so an 8 GB heap is generous and still leaves room for the rest of the build.
#
# Set in the `build` stage, not in `base`: the runtime image starts from a clean `node:22-slim` at the
# end of the Dockerfile, so this variable does not carry into the final image and does not change
# how the site behaves at run time.
#
# Since emdash@1.1.0 the upstream build stage sets its own `ENV NODE_OPTIONS=--max-old-space-size=4096`
# AFTER `COPY . .`, and a later ENV wins: a line inserted right under `FROM deps AS build` was
# overridden, and the presence check (`grep -q`) stayed green because it matched the upstream line.
# So: rewrite the upstream value when it is there, insert the line when it is not, and check by
# COUNT — every heap line in the file must read 8192.
if grep -q '^ENV NODE_OPTIONS=--max-old-space-size=' "$WORK/emdash/Dockerfile"; then
  sed -i 's|^ENV NODE_OPTIONS=--max-old-space-size=[0-9]*|ENV NODE_OPTIONS=--max-old-space-size=8192|' "$WORK/emdash/Dockerfile"
else
  sed -i 's|^FROM deps AS build|FROM deps AS build\nENV NODE_OPTIONS=--max-old-space-size=8192|' "$WORK/emdash/Dockerfile"
fi
HEAP_LINES="$(grep -c 'max-old-space-size=' "$WORK/emdash/Dockerfile" || true)"
HEAP_8G="$(grep -c 'max-old-space-size=8192' "$WORK/emdash/Dockerfile" || true)"
[ "$HEAP_8G" -ge 1 ] && [ "$HEAP_LINES" -eq "$HEAP_8G" ] \
  || { echo "!! build-stage heap is not 8 GB ($HEAP_LINES heap lines, $HEAP_8G at 8192) — upstream Dockerfile changed, read it" >&2; exit 1; }
echo "==> Node heap for the build stage: 8 GB"

echo "==> building (a few minutes, ~15 GB of scratch space)"
docker build -t "$IMAGE" "$WORK/emdash"

docker image inspect "$IMAGE" --format '==> done: {{.RepoTags}} {{.Size}} bytes'
