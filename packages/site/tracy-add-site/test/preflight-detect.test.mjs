import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { before, test } from 'node:test'

const require = createRequire(import.meta.url)
let inspectAddress
before(async () => {
  const { outputFiles } = await require('esbuild').build({
    entryPoints: [new URL('../src/host/detect.ts', import.meta.url).pathname],
    bundle: true,
    format: 'esm',
    platform: 'node',
    packages: 'external',
    write: false
  })
  ;({ inspectAddress } = await import(
    `data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`
  ))
})

const response =
  (html = '', init = {}) =>
  async () =>
    new Response(html, init)
const ADMIN = 'https://example.com/administrator/'
const FORM = `<form action="index.php"><input type="password" name="passwd"><input name="${'a'.repeat(32)}" value="1"></form>`

test('an answered unknown platform is distinct from no answer', async () => {
  const online = await inspectAddress('example.com', response('<html>Private platform</html>'))
  assert.deepEqual(online, { platform: null, reachable: true, secure: true, blocked: false, status: 200 })
  const offline = await inspectAddress('example.com', async () => {
    throw Object.assign(new Error('fetch failed'), { cause: { code: 'ENOTFOUND' } })
  })
  assert.equal(offline.reachable, false)
  assert.equal(offline.error, 'ENOTFOUND')
  assert.equal(offline.secure, null)
})

test('TLS rejection is separate from network failure and never retried over http', async () => {
  let calls = 0
  const answer = await inspectAddress('example.com', async () => {
    calls++
    throw Object.assign(new Error('fetch failed'), { cause: { code: 'CERT_HAS_EXPIRED' } })
  })
  assert.equal(calls, 1)
  assert.equal(answer.reachable, true)
  assert.equal(answer.secure, false)
  assert.equal(answer.error, 'CERT_HAS_EXPIRED')
})

test('Cloudflare protection warns while a named firewall challenge is identified as blocked', async () => {
  const protectedSite = await inspectAddress(
    'example.com',
    response('<meta name="generator" content="Joomla">', { headers: { server: 'cloudflare' } })
  )
  assert.equal(protectedSite.firewall, 'cloudflare')
  assert.equal(protectedSite.blocked, false)
  assert.equal(protectedSite.platform, 'joomla')
  const blocked = await inspectAddress('example.com', response('Generated by Wordfence', { status: 403 }))
  assert.equal(blocked.firewall, 'wordfence')
  assert.equal(blocked.blocked, true)
  assert.equal(blocked.reachable, true)
})

test('admin probe only GETs once with no credentials and does not infer captcha or MFA', async () => {
  const calls = []
  const answer = await inspectAddress(
    ADMIN,
    async (url, init) => {
      calls.push({ url, init })
      return new Response(`${FORM}<div>captcha</div><input name="secretkey">`)
    },
    true
  )
  assert.deepEqual(answer.admin, { signInFound: true, locked: false, basicAuthRequired: false })
  assert.equal(calls.length, 1)
  assert.equal(calls[0].init.method, undefined)
  assert.deepEqual(calls[0].init.headers, { 'user-agent': 'Tracy/1.0 (+https://tracy.ai)' })
  assert.equal(calls[0].init.body, undefined)
})

test('admin gates and wrong sign-in pages remain different; Basic auth is reported without trying it', async () => {
  const gate = await inspectAddress(
    ADMIN,
    response('<input type="password" name="rsf_backend_password">'),
    true
  )
  assert.deepEqual(gate.admin, { signInFound: false, locked: true, basicAuthRequired: false })
  const wrong = await inspectAddress(ADMIN, response('<html>Home</html>'), true)
  assert.deepEqual(wrong.admin, { signInFound: false, locked: false, basicAuthRequired: false })
  const basic = await inspectAddress(
    ADMIN,
    response('', { status: 401, headers: { 'www-authenticate': 'Basic realm="Admin"' } }),
    true
  )
  assert.deepEqual(basic.admin, { signInFound: null, locked: false, basicAuthRequired: true })
  assert.equal(basic.reachable, true)
})

test('front-end Joomla login is not the administrator sign-in', async () => {
  const answer = await inspectAddress(
    ADMIN,
    response(FORM.replace('index.php', '/index.php?option=com_users')),
    true
  )
  assert.equal(answer.admin.signInFound, false)
  assert.equal(answer.admin.locked, false)
})

test('WordPress admin checks its own sign-in form when selected', async () => {
  const answer = await inspectAddress(
    'https://example.com/wp-login.php',
    response('<form id="loginform"><input name="pwd"></form>'),
    true,
    'wordpress'
  )
  assert.equal(answer.admin.signInFound, true)
  assert.equal(answer.admin.locked, false)
})

test('unsafe schemes and redirects cannot become requests or reveal addresses', async () => {
  let calls = 0
  const invalid = await inspectAddress('https://user:password@example.com/', async () => {
    calls++
    return new Response('')
  })
  assert.equal(calls, 0)
  assert.equal(invalid.reachable, false)
  const redirected = await inspectAddress(
    'https://example.com/',
    response('', { status: 302, headers: { location: 'http://other.com/' } })
  )
  assert.equal(redirected.error, 'untrusted_redirect')
  assert.equal(JSON.stringify(redirected).includes('other.com'), false)
  const upper = await inspectAddress(
    'HTTPS://example.com/',
    response('', { status: 302, headers: { location: 'http://other.com/' } })
  )
  assert.equal(upper.error, 'untrusted_redirect')
})
