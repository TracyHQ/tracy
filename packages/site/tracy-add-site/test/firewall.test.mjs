#!/usr/bin/env node
/**
 * `firewallOf`: which gate answered instead of the site. Each case is the reply that product sends,
 * cut to the part the helper reads.
 */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'

import { firewallOf, gatewayOf, USER_AGENT } from '../src/host/firewall.mjs'

const headers = (pairs = {}) => new Headers(pairs)

test('Cloudflare: cf-mitigated on any status, the challenge page, or its block page', () => {
  assert.equal(firewallOf(200, headers({ 'cf-mitigated': 'challenge' }), ''), 'cloudflare')
  assert.equal(firewallOf(403, headers(), '<title>Just a moment...</title>'), 'cloudflare')
  assert.equal(firewallOf(503, headers(), '<script>window._cf_chl_opt={}</script>'), 'cloudflare')
  const blockPage =
    '<title>Attention Required! | Cloudflare</title><div id="cf-error-details"><h1>Sorry, you have been blocked</h1></div>'
  assert.equal(firewallOf(403, headers({ server: 'cloudflare' }), blockPage), 'cloudflare')
  // A site served through Cloudflare that answers its own 500 is not a block.
  assert.equal(firewallOf(500, headers({ server: 'cloudflare' }), 'Internal Server Error'), null)
})

test("a site's own 403 served through Cloudflare or Sucuri is not a block", () => {
  // The CDN's header is on every reply it relays, WordPress's own `wp_die` 403 included.
  const wpDie = '<body id="error-page">Sorry, you are not allowed to install plugins on this site.</body>'
  assert.equal(firewallOf(403, headers({ server: 'cloudflare' }), wpDie), null)
  assert.equal(
    firewallOf(503, headers({ server: 'cloudflare' }), 'Briefly unavailable for maintenance.'),
    null
  )
  assert.equal(firewallOf(403, headers({ 'x-sucuri-id': '1' }), wpDie), null)
  // Cloudflare's own page for an origin that is down is an error page, not a block.
  const originDown =
    '<title>example.com | 522: Connection timed out</title><div id="cf-error-details" class="cf-error-details-wrapper">'
  assert.equal(firewallOf(522, headers({ server: 'cloudflare' }), originDown), null)
})

test('Sucuri, Wordfence, Imunify360 and ModSecurity by their own pages', () => {
  assert.equal(firewallOf(200, headers({ 'x-sucuri-block': 'x' }), ''), 'sucuri')
  assert.equal(firewallOf(403, headers(), 'Access Denied - Sucuri Website Firewall'), 'sucuri')
  assert.equal(
    firewallOf(503, headers(), 'Your access to this site has been limited by the site owner'),
    'wordfence'
  )
  assert.equal(firewallOf(403, headers(), '<p>Generated by Wordfence at Mon</p>'), 'wordfence')
  assert.equal(firewallOf(403, headers(), 'Access denied by Imunify360 bot-protection'), 'imunify360')
  assert.equal(firewallOf(406, headers(), 'This error was generated by Mod_Security.'), 'modsecurity')
})

test('a page that only mentions a firewall on a 200 is not a block', () => {
  assert.equal(firewallOf(200, headers(), 'Wordfence settings — Generated by Wordfence'), null)
  assert.equal(firewallOf(200, headers(), '<title>Just a moment...</title>'), null)
})

test('generic: an unknown 403/406 page counts only when asked, and never a JSON answer', () => {
  assert.equal(firewallOf(403, headers(), '<html>Forbidden</html>'), null)
  assert.equal(firewallOf(403, headers(), '<html>Forbidden</html>', { generic: true }), 'firewall')
  assert.equal(firewallOf(406, headers(), '', { generic: true }), 'firewall')
  assert.equal(firewallOf(403, headers(), '{"ok":false,"error":"forbidden"}', { generic: true }), null)
  assert.equal(firewallOf(404, headers(), '<html>Not found</html>', { generic: true }), null)
  assert.equal(firewallOf(500, headers(), '<html>Error</html>', { generic: true }), null)
})

test('the one user agent names Tracy', () => {
  assert.match(USER_AGENT, /^Tracy\/\d/)
})

test("#1616 gatewayOf: only a page Cloudflare drew for a dead origin, never a proxy's own 502", () => {
  // Measured: a quick tunnel whose origin port refused connections.
  const tunnelPage = readFileSync(
    new URL('./fixtures/cloudflare-tunnel-origin-down-502.html', import.meta.url),
    'utf8'
  )
  const cf = headers({ server: 'cloudflare', 'cf-ray': '8d1f2e3a4b5c6d7e-AMS', 'retry-after': '60' })
  assert.equal(gatewayOf(502, cf, tunnelPage), 'cloudflare')
  assert.equal(firewallOf(502, cf, tunnelPage, { generic: true }), null, 'a dead origin is not a block')
  for (const status of [521, 522, 523, 530]) assert.equal(gatewayOf(status, cf, ''), 'cloudflare')
  // nginx's own page — what a host answers when php-fpm is overloaded or crashed — bare or relayed.
  const nginx502 =
    '<html><head><title>502 Bad Gateway</title></head><body><center><h1>502 Bad Gateway</h1></center><hr><center>nginx</center></body></html>'
  assert.equal(gatewayOf(502, headers({ server: 'nginx' }), nginx502), null)
  assert.equal(
    gatewayOf(502, cf, nginx502),
    null,
    'relayed through Cloudflare, it is still the origin talking'
  )
  assert.equal(gatewayOf(504, headers({ server: 'Apache' }), '<title>504 Gateway Time-out</title>'), null)
  assert.equal(gatewayOf(502, headers(), tunnelPage), null, 'the page without Cloudflare as the server')
  // The site's own PHP, served through Cloudflare or not.
  assert.equal(gatewayOf(500, cf, '<b>Fatal error</b>: Allowed memory size exhausted'), null)
  assert.equal(gatewayOf(503, headers({ 'retry-after': '120' }), 'Service Unavailable'), null)
  assert.equal(
    gatewayOf(524, cf, 'A timeout occurred'),
    null,
    '524: the origin took the call and ran out of time'
  )
})
