/**
 * Who answered instead of the site: a firewall, a WAF or a bot challenge in front of it.
 *
 * Every request Tracy makes to a customer's site can meet one, on either platform: Cloudflare's
 * "Just a moment..." challenge, a ModSecurity rule on the host, Wordfence's block page, Sucuri,
 * Imunify360. Each answers with its own page, and before this helper each page became whatever
 * the caller's generic failure was (`unreachable`, `install_failed`, `call_failed`) — a sentence
 * that sends the customer to check an address that was right all along.
 *
 * Plain JavaScript, like `doors.mjs`, so `node --test` pins it without a TypeScript loader. The
 * WordPress and export halves import it; the Joomla half can take it as it is.
 */

/**
 * The user agent every request to a customer's site carries.
 *
 * One value for the login, the installer AND the engine calls. Engine calls used to go out with
 * the runtime's default (`node`), which bot rules on shared hosting block outright while they let
 * the very same sign-in through — an import that got past the login and died on its first read.
 */
export const USER_AGENT = 'Tracy/1.0 (+https://tracy.ai)'

/**
 * Body markers, each tied to the product that prints it. Order matters: most specific first.
 * @type {Array<[string, RegExp]>}
 */
const BODY_MARKERS = [
  ['cloudflare', /<title>\s*Just a moment\.\.\.|\/cdn-cgi\/challenge-platform\/|_cf_chl_opt/i],
  ['sucuri', /Sucuri WebSite Firewall|sucuri\.net\/privacy-policy|Access Denied - Sucuri/i],
  [
    'wordfence',
    /Generated by Wordfence|Your access to this site has been limited by the site owner|wordfence\.com\/help\/\?query=locked-out/i
  ],
  ['imunify360', /Imunify360|imunify360-webshield/i],
  ['modsecurity', /Mod_?Security|This error was generated by Mod_Security/i]
]

/**
 * Cloudflare's block page (WAF rule, IP ban, rate limit). Its `cf-error-details` frame is shared
 * with the 52x pages Cloudflare draws for an origin that is down, so it counts only on the statuses
 * a block answers with.
 */
const CLOUDFLARE_BLOCK =
  /<title>\s*Attention Required! \| Cloudflare|Sorry, you have been blocked|cf-error-details/i

/**
 * @typedef {{ get(name: string): string | null }} HeaderBag
 */

/**
 * The firewall that answered, or `null` when nothing points to one.
 *
 * Header proof counts on any status: Cloudflare marks a challenge with `cf-mitigated` even on a
 * 200. Body proof counts only on an error status — a page that merely mentions Cloudflare or
 * Wordfence (a blog post, a plugin's settings screen) is not a block.
 *
 * 🔒 A CDN's identifying header (`server: cloudflare`, `x-sucuri-id`) is NOT proof: it rides every
 * reply the CDN relays, including WordPress's own `wp_die` 403 for a missing capability, which
 * must stay `no_backend_access`. Only a header the gate sets when it acts, or its own page, counts.
 *
 * `generic: true` also names an unrecognised `403`/`406` whose body is not JSON a `'firewall'`.
 * Callers pass it where the real application never answers that way — the WordPress login page,
 * an engine call — and leave it off where it does (`wp_die` answers a missing capability with 403).
 * @param {number} status HTTP status of the reply.
 * @param {HeaderBag} headers The reply's headers.
 * @param {string} body The reply's body, as text (a prefix is enough).
 * @param {{ generic?: boolean }} [options]
 * @returns {string | null} `cloudflare`, `sucuri`, `wordfence`, `imunify360`, `modsecurity`, `firewall`, or null.
 */
export function firewallOf(status, headers, body, options = {}) {
  if (headers.get('cf-mitigated')) return 'cloudflare'
  if (headers.get('x-sucuri-block')) return 'sucuri'
  if (status < 400) return null
  const text = body.slice(0, 64 * 1024)
  for (const [name, marker] of BODY_MARKERS) if (marker.test(text)) return name
  if ((status === 403 || status === 429) && CLOUDFLARE_BLOCK.test(text)) return 'cloudflare'
  if (options.generic && (status === 403 || status === 406) && !looksLikeJson(text)) return 'firewall'
  return null
}

/**
 * Did the application itself answer with JSON (Joomla's own 403 does), rather than a gate's page?
 * @param {string} text
 */
function looksLikeJson(text) {
  try {
    JSON.parse(text)
    return true
  } catch {
    return false
  }
}

/**
 * Statuses only Cloudflare's edge draws, each for an origin it could not reach: 521 the web server
 * refused the connection, 522 it timed out, 523 no route to it, 530 a tunnel with no origin behind
 * it. 524 is not here: the origin took the request and did not answer in time — the site's own PHP.
 */
const CLOUDFLARE_ORIGIN_DOWN = new Set([521, 522, 523, 530])

/**
 * The frame of the error page Cloudflare's edge draws itself. A tunnel whose origin refuses
 * connections answers it with 502 (measured 22/10/2026, `test/fixtures/cloudflare-tunnel-origin-down-502.html`):
 * cloudflared sends the edge a bodyless 502 and the edge draws this page.
 */
const CLOUDFLARE_ERROR_PAGE = /id="cf-error-details"|id="cf-wrapper"/i

/**
 * Cloudflare saying the site behind it is gone, or `null`.
 *
 * A Cloudflare tunnel whose origin went down answers every engine call 502 (measured on dev,
 * 22/10/2026, #1616); the 5xx used to be read as the site's PHP out of memory or time, and the
 * customer was sent to their host about PHP limits for a web server that was simply off.
 *
 * 🔒 Only a page Cloudflare DREW counts on a 502/504. A plain "502 Bad Gateway" from nginx or
 * Apache is also what a host's own proxy answers when php-fpm is overloaded or crashed — a real
 * resource limit — and Cloudflare relays that body unchanged, with its own `server` header on it.
 * @param {number} status HTTP status of the reply.
 * @param {HeaderBag} headers The reply's headers.
 * @param {string} body The reply's body, as text (a prefix is enough).
 * @returns {'cloudflare' | null}
 */
export function gatewayOf(status, headers, body) {
  if (CLOUDFLARE_ORIGIN_DOWN.has(status)) return 'cloudflare'
  if (status !== 502 && status !== 504) return null
  const edge = /^cloudflare$/i.test((headers.get('server') ?? '').trim())
  return edge && CLOUDFLARE_ERROR_PAGE.test(body.slice(0, 64 * 1024)) ? 'cloudflare' : null
}
