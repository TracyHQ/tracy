#!/usr/bin/env node
/**
 * Bundle the window shell (shell/*.ts) and `electron-updater` into src/generated/, where main.js and
 * the packaged app load them — the packaged app carries no node_modules.
 *
 * `@dsh-desktop/*` resolves into the dsh submodule's desktop app sources — imported, never copied, so
 * a dsh upgrade (moving the submodule) brings its window shell along. That app is a private dsh app,
 * not a package: when dsh renames or moves what is imported here, this build fails loudly, and that
 * is the signal to adjust shell/*.ts.
 *
 * The dsh packages those sources import resolve through this package's own dependencies (`nodePaths`),
 * which need dsh's libraries built (`pnpm dsh:build`), as every dsh consumer in this repo does.
 *
 *   node build/build-shell.mjs [outDir]
 */
import { build } from 'esbuild'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DSH_DESKTOP = path.resolve(PKG, '../../../vendor/tracy/deepseek-harness/apps/desktop/src')
const outDir = path.resolve(process.argv[2] ?? path.join(PKG, 'src/generated'))

const common = {
  bundle: true,
  format: 'cjs',
  target: 'node22',
  external: ['electron'],
  alias: { '@dsh-desktop': DSH_DESKTOP },
  nodePaths: [path.join(PKG, 'node_modules')],
  logLevel: 'warning',
  legalComments: 'inline',
  banner: { js: '// Generated by build/build-shell.mjs from shell/ and the dsh submodule. Do not edit.' }
}

await Promise.all([
  build({
    ...common,
    platform: 'node',
    entryPoints: [path.join(PKG, 'shell/main.ts')],
    outfile: path.join(outDir, 'shell-main.cjs')
  }),
  // A sandboxed preload is one file that may require only `electron`.
  build({
    ...common,
    platform: 'browser',
    entryPoints: [path.join(PKG, 'shell/preload.ts')],
    outfile: path.join(outDir, 'shell-preload.cjs')
  }),
  // The self-update library (src/updater.js), whole: a `require` esbuild could not follow would
  // fail only in the packaged app, where there is no node_modules to fall back on. The entry also
  // exposes the provider pieces src/signed-feed-provider.js builds on; the tests load the same entry.
  build({
    ...common,
    platform: 'node',
    entryPoints: [path.join(PKG, 'build/electron-updater-entry.cjs')],
    outfile: path.join(outDir, 'electron-updater.cjs')
  })
])
console.log(
  `build-shell: ${path.relative(PKG, outDir) || outDir}/{shell-main,shell-preload,electron-updater}.cjs`
)
