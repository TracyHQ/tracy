import path from 'node:path'
import { fileURLToPath } from 'node:url'

import type { StorybookConfig } from '@storybook/react-vite'

// @ts-expect-error — plain JS on purpose, with no type declarations: the same module runs inside
// `scripts/check-story-tags.mjs`, where there is no TypeScript program to lean on.
import { classify, findStories } from './story-kind.mjs'

const dirname = path.dirname(fileURLToPath(import.meta.url))

/**
 * Storybook for the design bench.
 *
 * WHY IT LIVES HERE AND NOT IN `vendor/shadcn-admin`. Tracy's stories used to live in the
 * shadcn-admin clone, and that was a dead end: `.gitignore` lines 58–69 declare
 * `vendor/shadcn-admin` a READ-ONLY template, not imported anywhere, so nothing Tracy drew there
 * was kept by any repo — lose the machine and it is gone, and nobody else can pull it. Measured
 * 02/09: `tracy-shell` and `tracy-no-sites` were both untracked there, next to upstream's own
 * nine story files.
 *
 * The framework is `react-vite`, NOT `tanstack-react` as in the vendor tree: the bench uses
 * `react-router-dom`, not TanStack Router. Copy the wrong framework and any story calling a
 * router hook dies at render.
 */
/**
 * Scan both story roots and return `{ path: label }`.
 *
 * Reads the disk directly rather than asking Storybook, because the table has to exist BEFORE
 * Vite builds the bundle.
 */
function storyKinds(): Record<string, string> {
  const roots = [path.resolve(dirname, '../src'), path.resolve(dirname, '../../../ui/tracy-ui/src')]
  const repoRoot = path.resolve(dirname, '../../../..')
  const table: Record<string, string> = {}
  for (const root of roots) {
    for (const file of findStories(root)) {
      const { kind } = classify(file)
      table[path.relative(repoRoot, file)] = kind
    }
  }
  return table
}

const config: StorybookConfig = {
  /**
   * TWO ROOTS, and the second lies outside this package — on purpose.
   *
   * A component's story lives NEXT TO the component, in `@tracy/ui`. That is the rule
   * `DESIGN.md` §0 already states ("write `.stories.tsx` next to the component") and also how
   * `vendor/shadcn-admin` does it. Gathering everything into the bench's `src/` separates a story
   * from what it describes, and what drifts apart goes stale: add a variant in `@tracy/ui` with
   * the story in another package and nobody remembers to update it.
   *
   * ⚠ A path through `node_modules` does NOT work here. `@tracy/ui` is `workspace:*`, so pnpm
   * plants a symlink; Vite follows symlinks, but Storybook's glob does not see through them — it
   * matches on the path string. So it must point straight at the source tree, three levels up,
   * exactly like `@source` in `src/style.css`.
   */
  stories: ['../src/**/*.stories.@(ts|tsx)', '../../../ui/tracy-ui/src/**/*.stories.@(ts|tsx)'],

  addons: ['@storybook/addon-a11y', '@storybook/addon-docs'],

  /**
   * TAG THE INDEX ITSELF, not each story file.
   *
   * This is the ONLY place that knows both the `importPath` and the stories produced from it,
   * so it is the only place a label can be attached without anyone typing it. Story authors
   * declare nothing, cannot forget, and cannot get it wrong.
   *
   * The tag rides along in `/index.json`, which is where `preview.tsx` reads it back from to
   * draw the banner.
   */
  experimental_indexers: (existing = []) =>
    existing.map((indexer) => ({
      ...indexer,
      createIndex: async (fileName: string, opts: unknown) => {
        const entries = await indexer.createIndex(fileName, opts)
        const { kind } = classify(fileName)
        return entries.map((entry) => ({ ...entry, tags: [...(entry.tags ?? []), `kind-${kind}`] }))
      }
    })),
  framework: '@storybook/react-vite',

  /**
   * 🔒 `__TAILWIND_CSS__` MUST BE DEFINED, OR PLUGIN STORIES DIE AT MODULE LOAD.
   *
   * Four mode-B plugins (`tracy-sidebar`, `tracy-settings`, `tracy-my-sites`, `tracy-add-site`)
   * have a `styles.ts` with `declare const __TAILWIND_CSS__` — a constant **esbuild replaces at
   * build time** (`scripts/build-client.mjs`), because dsh serves exactly one `lib/client.js` per
   * plugin, leaving no room for a second CSS file. Vite does not run that step, so left alone,
   * `import { CSS, TAILWIND } from './styles'` throws `ReferenceError` AT MODULE LOAD — before
   * render, so what shows up is a blank story rather than a wrong component.
   *
   * An empty string is correct, not a dodge: in Storybook the Tailwind classes are already
   * generated by the bench itself — `src/style.css` declares `@source` pointing at `src/client`
   * of all four plugins. Injecting a second copy of the CSS here would paint over itself.
   */
  viteFinal: async (config) => ({
    ...config,
    define: {
      ...config.define,
      __TAILWIND_CSS__: '""',
      /**
       * The classification table, COMPUTED AT STARTUP rather than written by hand.
       *
       * `classify()` walks each story's import graph and answers the one question a UI reviewer
       * needs: *does this screen exist, and do edits reach customers*. The label therefore cannot
       * be declared wrongly, because there is nowhere to type it.
       *
       * Keys are repo-relative paths, the same shape Storybook uses for `importPath`.
       *
       * ⚠ The table is fixed at startup: a NEW story needs a Storybook restart before its label
       * appears. Editing a story's contents does not — the label depends only on the graph.
       */
      __STORY_KINDS__: JSON.stringify(storyKinds())
    }
  }),

  typescript: {
    // The docs props table is generated from types, and `react-docgen-typescript` is the variant
    // that can read `React.ComponentProps<'button'> & VariantProps<typeof buttonVariants>` — the
    // shape every base-nova component uses. The default (`react-docgen`) misreads it and returns
    // an empty table.
    reactDocgen: 'react-docgen-typescript',
    reactDocgenTypescriptOptions: {
      /**
       * 🔒 A SEPARATE TSCONFIG, AND IT IS THE ONLY THING THAT FILLS THE PROPS TABLE.
       *
       * By default docgen reads this package's `tsconfig.json`, which has `include: ["src"]`, so
       * the 62 `@tracy/ui` components fall outside its TypeScript program. Docgen skips files
       * outside the program **silently from the user's side**: stories still run, docs pages are
       * still generated, only the props table is empty — nothing on screen says so.
       */
      tsconfigPath: path.resolve(dirname, 'tsconfig.docgen.json'),

      // 🔒 TWO GLOBS, BECAUSE THE DEFAULT ONLY SCANS INSIDE THE VITE ROOT.
      //
      // `tsconfigPath` above is NECESSARY, not SUFFICIENT. The plugin takes the INTERSECTION of two
      // sets: files in the TypeScript program AND files matching `include` — and `include` resolves
      // by default from the **Vite root** (`packages/dev/tracy-design`). All 62 `@tracy/ui`
      // components live outside that root, so the intersection is empty and the props table stays
      // blank even with the right tsconfig. Measured 03/09: fixing only `tsconfigPath` still logged
      // 67 "Skipping docgen" lines.
      //
      // The second glob is ABSOLUTE: `glob` takes the Vite root as `cwd`, and a relative pattern
      // crossing a package boundary works on one machine and breaks on another.
      //
      // ⚠ THIS COMMENT IS `//`, NOT `/** */`, AND THAT IS REQUIRED. The glob pattern contains a star
      // then a slash; written inside a JSDoc block it closes the block mid-sentence, and Storybook
      // dies in esbuild with `Expected identifier but found "."` — a message that never mentions
      // the comment. `pnpm typecheck` does not catch it: this package's `tsconfig.json` has
      // `include: ["src"]`, so the Storybook config sits outside every gate.
      include: ['**/*.tsx', `${path.resolve(dirname, '../../../ui/tracy-ui/src')}/**/*.tsx`],

      // Otherwise every component drags in ~250 lines of props inherited from HTMLAttributes.
      propFilter: (prop) => !/node_modules/.test(prop.parent?.fileName ?? '')
    }
  }
}

export default config
