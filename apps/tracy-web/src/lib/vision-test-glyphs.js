/** Lays out `text` with its baseline at (x, y) and returns one `<path>` in image coordinates. */
export function textPath(text, { x, y, size, fill = 'black' }) {
  const scale = size / UNITS_PER_EM
  const round = (n) => Math.round(n * 100) / 100
  let pen = 0
  let d = ''
  for (const char of text) {
    const glyph = GLYPHS[char]
    if (!glyph) throw Object.assign(new Error('VISION_GLYPH_MISSING'), { code: 'VISION_GLYPH_MISSING', char })
    const [advance, outline] = glyph
    // Every command uses absolute (x y) pairs, so each pair maps straight to image space.
    d += outline.replace(
      /(-?\d+) (-?\d+)/g,
      (_, gx, gy) => `${round(x + (pen + +gx) * scale)} ${round(y - +gy * scale)}`
    )
    pen += advance
  }
  return `<path d="${d}" fill="${fill}"/>`
}
