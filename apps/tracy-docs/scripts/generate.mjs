#!/usr/bin/env node
/**
 * Writes the three documentation pages that are TABLES, not prose, so they can never drift from the
 * code that answers the API:
 *
 *   src/content/docs/reference/errors.md         ← apps/tracy-web/src/api-reference/errors.js
 *   src/content/docs/reference/compatibility.md  ← apps/tracy-web/src/api-reference/actions.js
 *                                                   (+ the release table of sources/claude-cowork.js)
 *   src/content/docs/changelog.md                ← docs/references/api-changelog.md
 *
 * Runs first in `pnpm --filter @tracy/docs build` (package.json `build`), before `astro build`, and
 * the three outputs are gitignored: the source tables are the truth, a committed copy would be a
 * second one. No gate compares them — a page that is regenerated on every build has nothing to drift
 * from (tasks/todo-api-public.md Q6: "written by a script at build time, no gate of its own").
 *
 * WHAT IT DOES NOT IMPORT, AND WHY. `sites/route.js` holds `APPLY_RULES`, the toolset each action
 * needs — but that module reaches the database and the whole door; importing it here would make a
 * documentation build depend on `pg`. The toolset column therefore lives in the OpenAPI reference
 * (`/api/reference/`, where `app.js` hands the door tables to the spec builder) and this page says so.
 * `sources/claude-cowork.js` imports `lib/content-api.js`, which reads a schema off disk from
 * `packages/`; the one fact needed from it — the plugin releases the reference was read from — is
 * read from its text instead.
 *
 *   node scripts/generate.mjs            # writes the three pages
 *   node scripts/generate.mjs --out DIR  # writes them under DIR instead (tests)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { APPLY_ACTION_DOCS } from '../../tracy-web/src/api-reference/actions.js'
import { ERROR_DOCS } from '../../tracy-web/src/api-reference/errors.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const REPO = path.resolve(HERE, '../../..')
const COWORK_SOURCE = path.join(REPO, 'apps/tracy-web/src/api-reference/sources/claude-cowork.js')
const CHANGELOG_SOURCE = path.join(REPO, 'docs/references/api-changelog.md')
const DEFAULT_OUT = path.resolve(HERE, '../src/content/docs')

const GENERATED_NOTE =
  '<!-- GENERATED by apps/tracy-docs/scripts/generate.mjs at build time. Do not edit: change the source it names. -->'

/** Markdown table cell: pipes and newlines would break the row. */
const cell = (value) =>
  String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ')

function table(header, rows) {
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`)
  ].join('\n')
}

/**
 * How the `/v1` layer turns a plugin refusal (answered inside a 200 by the Apply door) into an HTTP
 * status — tasks/todo-api-public.md Q9. The Apply door itself keeps answering 200 + `{ok:false}`
 * so agents and plugins do not change; `/v1` normalises once, here documented once.
 */
export const V1_STATUS_MAP = [
  [
    '`bad_params`, `bad_action`, `CHANGES_INVALID`, `REVISION_REQUIRED`',
    400,
    'The request is wrong; fix the field the message names.'
  ],
  ['`refused`', 403, 'The plugin refuses this change by rule; do not retry the same call.'],
  ['`not_found`', 404, 'The record, table or file does not exist on the site.'],
  [
    '`unauthorized`',
    409,
    "Answered as `COMPONENT_UNAUTHORIZED`: the site no longer accepts Tracy's token; reconnect the site."
  ],
  [
    '`conflict`, `locked`, `writer_busy`, `revision_stale`, `REVISION_STALE`, `WRITER_BUSY`, `CONFLICT`, `SLOT_LOCKED_BY_USER`',
    409,
    'The site moved or is held; read again, wait, or have the lock released.'
  ],
  ['`too_large`', 413, 'More than the plugin carries in one call; send less.'],
  [
    '`contract_failed`, `contract_unavailable`, `contract_unbound`, `CONTRACT_FAILED`, every other `SLOT_*` code',
    422,
    'The content contract refused the change; `errors[]` names each slot and rule.'
  ],
  [
    '`PRESENTATION_DRIFT`',
    422,
    "Only when it comes as a refusal (older plugin releases); as `severity: warning` beside a normal answer the status is the answer's own."
  ],
  ['`unsupported`, `unavailable`', 501, 'This site cannot do what was asked; do not retry the same call.'],
  [
    '`<verb>_failed`, `fatal`',
    500,
    'The site failed while handling the call; read the site before any retry.'
  ]
]

function errorsPage() {
  const families = [
    {
      family: 'door',
      heading: 'Refusals from Tracy',
      intro:
        'Answered by Tracy itself, before or around the call to the site, with the HTTP status shown. On `/v1` the body is `{ "error": { "code", "message" }, "next" }`; the key-layer codes (`KEY_INVALID`, `KEY_REVOKED`, `KEY_EXPIRED`, `RATE_LIMITED`) are on the [Authentication](/authentication/) page.'
    },
    {
      family: 'content',
      heading: 'Refusals of a Content API read',
      intro:
        'Answered for `GET /v1/sites/{key}` (describe), `…/pages`, `…/contents`, `…/contents/{id}` and `…/changes`, with the HTTP status shown.'
    },
    {
      family: 'plugin',
      heading: 'Answers from the site',
      intro:
        'What the Claude Cowork plugin on the site refuses. The Apply door relays these unchanged inside a `200` as `{ "ok": false, "error": "<code>", "message" }`; a contract refusal lists one entry per slot in `errors[]`, each with a `code` from the second half of this table. **On `/v1` these are mapped to an HTTP status once** — see the table below — and the body keeps `errors[]` and `next`.'
    }
  ]
  const lines = [
    '---',
    'title: Errors',
    "description: Every refusal the API can answer — Tracy's own, the Content API's, and the site's — with what happened and what to do next, plus the HTTP status each plugin code gets on /v1.",
    '---',
    '',
    GENERATED_NOTE,
    '',
    'Every refusal carries a `code`, one sentence on what happened (`message`) and, where Tracy knows it, `next`: what to do. This page lists all of them, generated from the same table the [OpenAPI reference](/reference/) is built from.',
    ''
  ]
  for (const { family, heading, intro } of families) {
    const rows = ERROR_DOCS.filter((e) => e.family === family)
    lines.push(`## ${heading}`, '', intro, '')
    lines.push(
      table(
        family === 'plugin'
          ? ['Code', 'Meaning', 'What to do next']
          : ['Status', 'Code', 'Meaning', 'What to do next'],
        rows.map((e) =>
          family === 'plugin'
            ? [`\`${e.code}\``, e.meaning, e.next]
            : [String(e.status), `\`${e.code}\``, e.meaning, e.next]
        )
      ),
      ''
    )
  }
  lines.push(
    '## HTTP status of a site answer on `/v1`',
    '',
    'The Apply door (`POST /api/sites/{key}/apply`, used by the Tracy agent) answers a site refusal as `200` + `{ "ok": false }`, and that does not change. The `/v1` layer maps the same codes to a status once, so an HTTP client can branch on it. The body keeps the code, the message, `errors[]` and `next`.',
    '',
    table(
      ['Plugin code', 'HTTP status', 'Read as'],
      V1_STATUS_MAP.map(([codes, status, meaning]) => [codes, String(status), meaning])
    ),
    ''
  )
  return lines.join('\n')
}

/** `RELEASES = { joomla: '0.18.4', wordpress: '0.14.3' }` from the plugin document's source text. */
export function documentedReleases(sourceText) {
  const match = /export const RELEASES = \{([^}]+)\}/.exec(sourceText)
  if (!match) throw new Error(`RELEASES not found in ${COWORK_SOURCE}`)
  const releases = {}
  for (const pair of match[1].matchAll(/(\w+):\s*'([^']+)'/g)) releases[pair[1]] = pair[2]
  if (!releases.joomla || !releases.wordpress) throw new Error(`RELEASES incomplete: ${match[1]}`)
  return releases
}

const PLATFORMS = [
  ['joomla', 'Joomla'],
  ['wordpress', 'WordPress'],
  ['emdash', 'EmDash']
]

/** The `/v1` route each Apply action stands behind, where one does (tasks/todo-api-public.md S3). */
const V1_ROUTES = {
  'content.read': '`GET /v1/sites/{key}` · `…/pages` · `…/contents` · `…/contents/{id}` · `…/changes`',
  'content.list': '`GET /v1/sites/{key}/records/{kind}`',
  'content.get': '`GET /v1/sites/{key}/records/{kind}/{id}`',
  'content.update': '`PATCH /v1/sites/{key}/records/{kind}/{id}`',
  'content.delete': '`DELETE /v1/sites/{key}/records/{kind}/{id}`',
  'content.contract': '`POST /v1/sites/{key}/contract/{operation}`',
  'apply.list': '`GET /v1/sites/{key}/applies/{id}`',
  'apply.revert': '`POST /v1/sites/{key}/applies/{id}/revert`'
}

function compatibilityPage(releases) {
  const versionCell = (doc, platform) => {
    if (!doc.platforms.includes(platform)) return '—'
    if (platform === 'emdash') return 'Tracy reader'
    return doc.requires?.[platform] ? `≥ ${doc.requires[platform]}` : 'every release'
  }
  const rows = Object.entries(APPLY_ACTION_DOCS)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([action, doc]) => [
      `\`${action}\``,
      doc.writes ? 'write' : 'read',
      ...PLATFORMS.map(([id]) => versionCell(doc, id)),
      V1_ROUTES[action] ?? 'Apply door only'
    ])
  return [
    '---',
    'title: Compatibility',
    'description: Every action of the Apply door — which platforms answer it, the minimum Claude Cowork plugin release per platform, whether it writes, and the /v1 route it stands behind.',
    '---',
    '',
    GENERATED_NOTE,
    '',
    `Generated from the action table of the API reference. The reference itself was read against Claude Cowork **Joomla ${releases.joomla}** and **WordPress ${releases.wordpress}**; a site's own release is in the answer of \`GET /v1/sites/{key}\` (describe) or of the Apply action \`info\`.`,
    '',
    '- **Minimum release** is the plugin release that first answered the action; an older site answers `400 bad_action`. "every release" means the action is as old as the plugin.',
    "- **EmDash** sites have no plugin: reads are answered by Tracy's own reader, writes are not answered through Tracy (see the [EmDash guide](/guides/emdash/)).",
    "- The **toolset** each action needs (`content`, `code`, `site`, `lifecycle`) is not on this page: it comes from the door's own rules and is printed beside each action in the [OpenAPI reference](/reference/).",
    '- "Apply door only" means the action exists for the Tracy agent (`POST /api/sites/{key}/apply` on Tracy\'s own hostname) and has no `/v1` route yet.',
    '',
    table(['Action', 'Kind', ...PLATFORMS.map(([, label]) => label), '/v1 route'], rows),
    ''
  ].join('\n')
}

/** The public changelog as a Starlight page: front matter replaced, H1 dropped (the title is the frontmatter). */
export function changelogPage(sourceText) {
  const body = sourceText.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '').replace(/^# .*\r?\n/m, '')
  return [
    '---',
    'title: Changelog',
    'description: Dated record of every change to the public Tracy API — what was added, changed or removed, and when.',
    '---',
    '',
    GENERATED_NOTE,
    '',
    body.trim(),
    ''
  ].join('\n')
}

export function generate(outDir = DEFAULT_OUT) {
  const releases = documentedReleases(readFileSync(COWORK_SOURCE, 'utf8'))
  const pages = {
    'reference/errors.md': errorsPage(),
    'reference/compatibility.md': compatibilityPage(releases),
    'changelog.md': changelogPage(readFileSync(CHANGELOG_SOURCE, 'utf8'))
  }
  for (const [rel, text] of Object.entries(pages)) {
    const file = path.join(outDir, rel)
    mkdirSync(path.dirname(file), { recursive: true })
    writeFileSync(file, text)
  }
  return Object.keys(pages)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--out')
  const written = generate(i >= 0 ? path.resolve(process.argv[i + 1]) : DEFAULT_OUT)
  process.stdout.write(`generate: wrote ${written.join(', ')}\n`)
}
