/**
 * `scripts/generate.mjs` writes the three table pages of the documentation site from the reference
 * tables. What is pinned: every error code and every action reaches its page (a code added to
 * `errors.js` without a row here would be a silently incomplete public page), the `/v1` status map
 * covers every plugin code the table knows, the changelog keeps its English body and loses its
 * Vietnamese-facing front matter, and no page carries Vietnamese.
 */
import assert from 'node:assert/strict'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { test } from 'node:test'

import { APPLY_ACTION_DOCS } from '../../tracy-web/src/api-reference/actions.js'
import { ERROR_DOCS } from '../../tracy-web/src/api-reference/errors.js'
import { changelogPage, documentedReleases, generate, V1_STATUS_MAP } from '../scripts/generate.mjs'

const VIETNAMESE =
  /[àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđÀÁẢÃẠĂẰẮẲẴẶÂẦẤẨẪẬÈÉẺẼẸÊỀẾỂỄỆÌÍỈĨỊÒÓỎÕỌÔỒỐỔỖỘƠỜỚỞỠỢÙÚỦŨỤƯỪỨỬỮỰỲÝỶỸỴĐ]/

function generated(t) {
  const out = mkdtempSync(path.join(tmpdir(), 'tracy-docs-gen-'))
  t.after(() => rmSync(out, { recursive: true, force: true }))
  const written = generate(out)
  const read = (rel) => readFileSync(path.join(out, rel), 'utf8')
  return { written, read }
}

test('writes the three pages, each with Starlight front matter and a generated marker', (t) => {
  const { written, read } = generated(t)
  assert.deepEqual(written.sort(), ['changelog.md', 'reference/compatibility.md', 'reference/errors.md'])
  for (const rel of written) {
    const text = read(rel)
    assert.match(text, /^---\ntitle: .+\ndescription: .+\n---\n/, rel)
    assert.match(text, /GENERATED by apps\/tracy-docs\/scripts\/generate\.mjs/, rel)
    assert.doesNotMatch(text, VIETNAMESE, `${rel} carries Vietnamese`)
  }
})

test('errors: every code of every family is a row, and the /v1 status map names a status for each plugin code family', (t) => {
  const { read } = generated(t)
  const page = read('reference/errors.md')
  for (const { code } of ERROR_DOCS) assert.ok(page.includes(`\`${code}\``), `missing ${code}`)
  for (const heading of [
    'Refusals from Tracy',
    'Refusals of a Content API read',
    'Answers from the site',
    'HTTP status of a site answer on `/v1`'
  ])
    assert.ok(page.includes(`## ${heading}`), heading)
  // Every plugin-family code is mentioned in the mapping table, either by name or by a family pattern.
  const mapped = V1_STATUS_MAP.map(([codes]) => codes).join(' ')
  for (const { code, family } of ERROR_DOCS) {
    if (family !== 'plugin') continue
    const named = mapped.includes(`\`${code}\``)
    const byPattern =
      (code.endsWith('_failed') && mapped.includes('`<verb>_failed`')) ||
      (code.startsWith('SLOT_') && mapped.includes('`SLOT_*`'))
    assert.ok(named || byPattern, `plugin code ${code} has no /v1 status`)
  }
  for (const [, status] of V1_STATUS_MAP) assert.ok([400, 403, 404, 409, 413, 422, 500, 501].includes(status))
})

test('compatibility: every action is a row with its platforms, minimum release and /v1 route or "Apply door only"', (t) => {
  const { read } = generated(t)
  const page = read('reference/compatibility.md')
  for (const [action, doc] of Object.entries(APPLY_ACTION_DOCS)) {
    const row = page.split('\n').find((line) => line.startsWith(`| \`${action}\` |`))
    assert.ok(row, `missing ${action}`)
    const cells = row.split('|').map((c) => c.trim())
    // | action | kind | Joomla | WordPress | EmDash | /v1 route |
    assert.equal(cells[2], doc.writes ? 'write' : 'read', action)
    assert.equal(
      cells[3],
      doc.platforms.includes('joomla')
        ? doc.requires?.joomla
          ? `≥ ${doc.requires.joomla}`
          : 'every release'
        : '—',
      action
    )
    assert.equal(
      cells[4],
      doc.platforms.includes('wordpress')
        ? doc.requires?.wordpress
          ? `≥ ${doc.requires.wordpress}`
          : 'every release'
        : '—',
      action
    )
    assert.equal(cells[5], doc.platforms.includes('emdash') ? 'Tracy reader' : '—', action)
    assert.ok(cells[6].startsWith('`') || cells[6] === 'Apply door only', `${action}: ${cells[6]}`)
  }
  assert.match(
    page,
    /Joomla \*\*Joomla 0\.\d+\.\d+\*\*|Claude Cowork \*\*Joomla 0\.\d+\.\d+\*\* and \*\*WordPress 0\.\d+\.\d+\*\*/
  )
})

test('documentedReleases reads the plugin document’s RELEASES and refuses when it is gone', () => {
  assert.deepEqual(documentedReleases("export const RELEASES = { joomla: '0.18.4', wordpress: '0.14.3' }"), {
    joomla: '0.18.4',
    wordpress: '0.14.3'
  })
  assert.throws(() => documentedReleases('export const NOTHING = 1'), /RELEASES not found/)
  assert.throws(() => documentedReleases("export const RELEASES = { joomla: '1' }"), /incomplete/)
})

test('changelog: front matter and the H1 are replaced, the dated body is kept', () => {
  const page = changelogPage(
    '---\ndescription: x\nsources:\n  - a.js\n---\n\n# Tracy API changelog\n\nIntro line.\n\n## 2026-09-28\n\n- **Thing** added.\n'
  )
  assert.match(page, /^---\ntitle: Changelog\n/)
  assert.doesNotMatch(page, /sources:/)
  assert.doesNotMatch(page, /# Tracy API changelog/)
  assert.match(page, /## 2026-09-28\n\n- \*\*Thing\*\* added\./)
})
